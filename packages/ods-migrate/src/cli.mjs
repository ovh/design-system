/** A file of the --json report (version 3): the same words as the text report, and a stable id per item to track. */
function jsonFile(result) {
  const seen = new Map();
  const withId = (site) => {
    const base = createHash('sha1').update(`${result.file}\0${site.message}`).digest('hex').slice(0, 10);
    const count = (seen.get(base) ?? 0) + 1;
    seen.set(base, count);
    return { id: count > 1 ? `${base}-${count}` : base, ...site };
  };
  return {
    file: result.file,
    package: result.package,
    changed: result.changed,
    markersAdded: result.markersAdded,
    from: result.from,
    changes: result.changes,
    markers: result.todos.map(withId),
    toCheck: result.notes.map(withId),
    typeCheck: result.typed.map(withId),
    untyped: result.untyped.map(withId),
    looks: result.looks.map(({ component, ...site }) => site),
    notOds: result.notOds,
    existingMarkers: result.existingMarkers,
    ...(result.error ? { error: result.error, errorCode: result.errorCode } : {}),
  };
}

/** The config files next to or above the scanned paths that the run does not read (it reads the one of the cwd, or --config). */
function unusedConfigs(roots, used, name) {
  const found = new Set();
  for (const root of roots) {
    let dir = statSync(root).isDirectory() ? root : dirname(root);
    for (;;) {
      const candidate = join(dir, name);
      if (existsSync(candidate) && resolve(candidate) !== (used && resolve(used))) {
        found.add(candidate);
        break;
      }
      if (existsSync(candidate) || dirname(dir) === dir) {
        break;
      }
      dir = dirname(dir);
    }
  }
  return [...found];
}

/**
 * The package names under the top-level `overrides:` of a pnpm-workspace.yaml (pnpm reads them there
 * too; pnpm 11 only there), an empty list when it has none. A small reader: keys indented under
 * `overrides:`, quoted or not.
 */
function workspaceOverridesOf(path) {
  let text;
  try {
    text = readFileSync(path, 'utf8');
  } catch {
    return null;
  }
  const lines = text.split(/\r?\n/);
  const start = lines.findIndex((line) => /^overrides:\s*(#.*)?$/.test(line));
  if (start === -1) {
    return [];
  }
  const names = [];
  for (const line of lines.slice(start + 1)) {
    if (/^\S/.test(line)) break;
    const key = line.match(/^\s+(?:'([^']+)'|"([^"]+)"|([^\s:#'"][^:#]*?))\s*:/);
    if (key) names.push(key[1] ?? key[2] ?? key[3]);
  }
  return names;
}

/** The highest React major declared by the scanned package.json files (for the overrides of a root). */
function workspaceReactMajor(manifests) {
  let major = null;
  for (const path of manifests) {
    try {
      const manifest = JSON.parse(readFileSync(path, 'utf8'));
      const range = manifest.dependencies?.react ?? manifest.devDependencies?.react ?? manifest.peerDependencies?.react;
      const found = minMajor(range);
      if (found !== null && (major === null || found > major)) {
        major = found;
      }
    } catch {
      // Reported by the manifest pass.
    }
  }
  return major;
}

/** The report file: its directory exists and is writable, and it is not a directory itself. */
function checkWritableTarget(path, flag) {
  const dir = dirname(path);
  let dirStat;
  try {
    dirStat = statSync(dir);
  } catch {
    throw new FileError(`${flag} ${path}: the directory ${dir} does not exist`);
  }
  if (!dirStat.isDirectory()) {
    throw new FileError(`${flag} ${path}: ${dir} is not a directory`);
  }
  if (existsSync(path) && statSync(path).isDirectory()) {
    throw new FileError(`${flag} ${path}: is a directory`);
  }
  try {
    accessSync(existsSync(path) ? path : dir, constants.W_OK);
  } catch {
    throw new FileError(`${flag} ${path}: permission denied`);
  }
}

/** The opt-out CSS is only ever overwritten when ods-migrate wrote it. */
function checkOptOutTarget(path) {
  checkWritableTarget(path, 'optOutCss');
  if (existsSync(path) && !readFileSync(path, 'utf8').startsWith(OPT_OUT_HEADER)) {
    throw new FileError(`optOutCss ${path}: the file exists and was not generated by ods-migrate: move it, or set another optOutCss in the config`);
  }
}

const isMain = (() => {
  try {
    return Boolean(process.argv[1]) && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
})();

if (isMain) {
  const code = await run(process.argv.slice(2));
  // Exit once the output is flushed, without waiting for the native parser's teardown, which
  // crashes (SIGSEGV) after a large file.
  let pending = 2;
  const done = () => --pending || process.exit(code);
  process.stdout.write('', done);
  process.stderr.write('', done);
}

