/*
 * The changes whose v20 form is not final yet (`pending` entries of the mappings, not enabled by the
 * config): the names they are about, to count the files that would change if they were applied.
 */
function notFinalSubjects(mapping, tokenMapping, config) {
  const enabled = new Set(config?.pending ?? []);
  const subjects = new Map();
  const add = (id, label, names) => {
    if (enabled.has(id) || !names.length) return;
    const key = `${id}\0${label}`;
    const subject = subjects.get(key) ?? { files: new Set(), id, label, names: new Set() };
    names.forEach((name) => subject.names.add(name));
    subjects.set(key, subject);
  };
  for (const [component, spec] of Object.entries(mapping.components ?? {})) {
    if (spec.pending) add(spec.pending, component, [component]);
    for (const rule of Object.values(spec.props ?? {})) {
      if (rule.pending) add(rule.pending, component, [component]);
    }
  }
  for (const [name, rule] of Object.entries(mapping.exports ?? {})) {
    if (rule.pending && /^[A-Z][a-z]+[A-Za-z]*$/.test(name) && !/(Prop|Size|Sizes|Detail)$/.test(name)) add(rule.pending, name.replace(/Item$/, ''), [name]);
  }
  for (const table of ['tokens', 'scss']) {
    for (const [name, entry] of Object.entries(tokenMapping[table] ?? {})) {
      if (entry.pending) add(entry.pending, `${name.match(/^(--|\$)ods-[a-z]+/)?.[0] ?? name}-* tokens`, [name]);
    }
  }
  const list = [...subjects.values()].map((subject) => ({ ...subject, test: new RegExp(`(?:^|[^\\w$-])(?:${[...subject.names].map((name) => name.replace(/[$.*+?^{}()|[\]\\/]/g, '\\$&')).join('|')})(?![\\w-])`) }));
  return {
    ids: [...new Set(list.map(({ id }) => id))],
    pattern: list.length ? new RegExp(list.map(({ test }) => test.source).join('|')) : /$^/,
    report: () => {
      const byLabel = new Map();
      for (const subject of list.filter(({ files }) => files.size)) {
        const item = byLabel.get(subject.label) ?? { files: new Set(), name: subject.label };
        subject.files.forEach((file) => item.files.add(file));
        byLabel.set(subject.label, item);
      }
      return [...byLabel.values()].map(({ files, name }) => ({ files: files.size, name })).sort((a, b) => b.files - a.files || (a.name < b.name ? -1 : 1));
    },
    subjects: list,
  };
}

