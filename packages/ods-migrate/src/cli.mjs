/*
 * One file: how many changes (the patch, --diff, shows them), then what needs a person, by line:
 * the markers added (⚠), the points to check (?), the values for the type check (type) and, with
 * --check, the values of untyped code and the markers already there.
 */
function printFile(io, result, check) {
  if (result.error) {
    return;
  }
  const lines = [
    ...result.todos.map((site) => [site.line, `⚠ ${TODO} ${site.message}`]),
    ...result.notes.map((site) => [site.line, `? ${site.message}`]),
    ...result.typed.map((site) => [site.line, `type ${site.message}`]),
    ...(check ? result.untyped.map((site) => [site.line, `untyped ${site.message}`]) : []),
    ...(check ? result.existingMarkers.map((line) => [line, `⚠ ${TODO} (already in the code)`]) : []),
  ].sort((a, b) => a[0] - b[0]);
  if (!lines.length && !result.changed) {
    return;
  }
  const what = [
    result.changes.length ? plural(result.changes.length, 'change') : null,
    result.markersAdded ? plural(result.markersAdded, 'marker') : null,
  ].filter(Boolean).join(', ');
  print(io);
  print(io, `${result.file}${what ? ` (${what})` : ''}`);
  for (const [line, message] of lines) {
    print(io, `  ${String(line).padStart(4)}  ${message}`);
  }
}

