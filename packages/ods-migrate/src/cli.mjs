/**
 * The ODS major a file is written for: the range of @ovhcloud/ods-react in the nearest package.json
 * that declares it or one of the --also packages. Unknown (a UI kit only, a workspace range) → 19.
 */
function createFromResolver(packages) {
  const cache = new Map();
  // { from, manifest }: the major, and the package.json that says it (null when none does).
  const lookup = (dir) => {
    if (cache.has(dir)) {
      return cache.get(dir);
    }
    let result;
    try {
      const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
      const blocks = ['dependencies', 'devDependencies', 'peerDependencies'].map((key) => manifest?.[key] ?? {});
      const range = blocks.map((block) => block[ODS_PACKAGE]).find((value) => value !== undefined);
      if (range !== undefined) {
        result = { from: minMajor(range) ?? DEFAULT_FROM, manifest: join(dir, 'package.json'), range };
      } else if (packages.some((name) => name !== ODS_PACKAGE && blocks.some((block) => block[name] !== undefined))) {
        result = { from: DEFAULT_FROM, manifest: join(dir, 'package.json') };
      }
    } catch {
      // No package.json here, or not one we can read: look further up.
    }
    if (result === undefined) {
      result = dirname(dir) === dir ? { from: DEFAULT_FROM, manifest: null } : lookup(dirname(dir));
    }
    cache.set(dir, result);
    return result;
  };
  const fromOf = (file) => lookup(dirname(file)).from;
  fromOf.origin = (file) => lookup(dirname(file));
  return fromOf;
}

/* ------------------------------------------------------------------------- line mapping */

/**
 * For each line of `after` (0-based), the 1-based line of `before` it comes from. The component
 * pass only edits locally, so both texts are aligned line by line and resynchronized within a small
 * window after a difference: linear, unlike a full diff, on files with thousands of edits.
 */
function alignLines(before, after, window = 40) {
  const a = before.split('\n');
  const b = after.split('\n');
  const map = new Array(b.length);
  let i = 0;
  let j = 0;
  while (j < b.length) {
    if (i < a.length && a[i] === b[j]) {
      map[j++] = ++i;
      continue;
    }
    let sync = null;
    for (let distance = 1; distance <= window && !sync; distance++) {
      for (let k = 0; k <= distance; k++) {
        const l = distance - k;
        if (i + k < a.length && j + l < b.length && a[i + k] === b[j + l] && a[i + k].trim() !== '') {
          sync = [k, l];
          break;
        }
      }
    }
    if (!sync) {
      map[j++] = Math.min(i + 1, a.length);
      i++;
      continue;
    }
    const [k, l] = sync;
    for (let step = 0; step < l; step++) {
      map[j + step] = Math.min(i + Math.min(step, Math.max(k - 1, 0)) + 1, a.length);
    }
    i += k;
    j += l;
  }
  return map;
}

/** Lines of the markers already in a text, 1-based. */
function markerLines(text) {
  const lines = [];
  let line = 1;
  let last = 0;
  for (const match of text.matchAll(MARKER)) {
    for (let index = text.indexOf('\n', last); index !== -1 && index < match.index; index = text.indexOf('\n', index + 1)) {
      line++;
      last = index + 1;
    }
    lines.push(line);
  }
  return lines;
}

const countMarkers = (text) => text.match(MARKER)?.length ?? 0;
const byLine = (a, b) => a.line - b.line;

