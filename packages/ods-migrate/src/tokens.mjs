/*
 * Rewrites the tokens of a CSS value; the property gives the role, a gradient takes it away,
 * a calc() or Sass arithmetic makes it computed.
 */
function migrateValue(mapping, value, context, plan) {
  const { hasToken } = patternsOf(mapping);
  const parsed = valueParser(value);
  // `var(--ods-color-primary-500)` or `var(--ods-color-primary-500, #hex)` alone: the whole value is one token.
  const top = parsed.nodes.filter((node) => node.type !== 'space');
  const single = top.length === 1 && top[0].type === 'function' && top[0].value === 'var';
  const visit = (nodes, calls) => {
    const arithmetic = nodes.some((node) => node.type === 'word' && /^[-+*/%]$/.test(node.value));
    const inGradient = calls.some((name) => GRADIENT.test(name));
    const local = { ...context, likely: context.likely ?? context.role, math: arithmetic || calls.some((name) => MATH.test(name)), role: inGradient ? null : context.role };
    nodes.forEach((node, index) => {
      if (node.type === 'word' && node.value.startsWith('--ods-') && node.value.includes('#{')) {
        const prefix = node.value.slice(0, node.value.indexOf('#{'));
        if (isTokenPrefix(mapping, prefix)) plan.todos.push(`${prefix}#{…}: token name built at runtime: map each value by hand`);
      } else if (node.type === 'word' && node.value.startsWith('--ods-') && hasToken.test(node.value)) {
        const name = node.value;
        if (isOverrideOnly(mapping, name)) return;
        const result = resolveToken(mapping, name, { ...local, whole: single && calls.length === 1 && nodes[0] === node });
        if (result.to) {
          node.value = result.to;
          plan.changes.push(`${name} → ${result.to}`);
        }
        if (result.todo) plan.todos.push(result.todo);
        if (result.note) plan.notes.push(result.note);
      } else if ((node.type === 'word' || node.type === 'string') && /--ods-/.test(node.value)) {
        // A Tailwind class (`bg-[--ods-…]`) or a quoted SCSS string: read like a script string.
        const key = node.type === 'string' && nodes[index - 1]?.type === 'div' && nodes[index - 1].value === ':' && nodes[index - 2]?.type === 'string'
          ? roleOfProperty(`--${nodes[index - 2].value}`)
          : undefined;
        const text = planText(mapping, node.value, { config: context.config, css: node.type === 'string', hashed: false, role: key === undefined ? local.role : key, themeKeys: context.themeKeys });
        node.value = applyEdits(node.value, text.edits);
        text.edits.forEach((item) => plan.changes.push(item.message));
        plan.todos.push(...text.todos);
        plan.notes.push(...text.notes);
      }
      if (node.type === 'function') {
        visit(node.nodes, [...calls, node.value]);
      }
    });
  };
  visit(parsed.nodes, []);
  return renameFont(parsed.toString(), plan, context.config);
}

/* The v19 font family (unless the config keeps it) and the font folder of the ODS package (in a url() too). */
function renameFont(text, plan, config) {
  return text
    .replace(OLD_FONT, (match, quote) => {
      if (keepsOldFont(config)) return match;
      plan.changes.push('\'Source Sans Pro\' → \'Source Sans 3\'');
      return `${quote || '\''}Source Sans 3${quote || '\''}`;
    })
    .replace(OLD_FONT_PATH, (match, folder) => {
      plan.changes.push('source-sans-pro → source-sans-3');
      return `${folder}source-sans-3`;
    });
}

/* The SCSS variables a stylesheet declares itself: a homonym of a removed ODS variable is its own. */
const ownVariables = new WeakMap();
function variablesOf(root) {
  if (!ownVariables.has(root)) {
    const names = new Set();
    root.walkDecls(/^\$/, (decl) => names.add(decl.prop));
    ownVariables.set(root, names);
  }
  return ownVariables.get(root);
}

/*
 * The module namespaces under which the stylesheet reads `@ovhcloud/ods-themes` (`@use … as v`
 * → `v.$…`), and whether it reads it without one (`@import`, `@use … as *`).
 */
const themesImports = new WeakMap();
function themesOf(root) {
  if (!themesImports.has(root)) {
    const info = { bare: false, namespaces: new Set() };
    root.walkAtRules(/^(use|import)$/, (rule) => {
      if (!THEMES_IMPORT.test(rule.params)) return;
      if (rule.name === 'import') {
        info.bare = true;
        return;
      }
      const use = rule.params.match(/^\s*(['"])([^'"]*)\1(?:\s+as\s+([\w*-]+))?/);
      if (!use) return;
      if (use[3] === '*') info.bare = true;
      else info.namespaces.add(use[3] ?? use[2].split('/').pop().replace(/^_/, '').replace(/\.s?css$/, ''));
    });
    themesImports.set(root, info);
  }
  return themesImports.get(root);
}
const readsThemes = (root) => themesOf(root).bare || themesOf(root).namespaces.size > 0;

/* Inside a Sass function call, or the params of a Sass control rule, a var() cannot be computed. */
const sassComputes = (text, index, atRule) => SASS_CONTROL.test(atRule ?? '') || openCalls(text.slice(0, index)).some((name) => SASS_FUNCTION.test(name));

/*
 * Rewrites the removed SCSS variables of `@ovhcloud/ods-react/style` in a value or in at-rule
 * params: a rename keeps the module namespace, a replacement value drops it. `keep` names
 * survive in v20 with another meaning: marked or noted, never rewritten.
 */
function migrateVariables(mapping, text, own, plan) {
  return text.replace(patternsOf(mapping).scss, (match, namespace = '', bare) => {
    const name = `$${bare}`;
    if (!namespace && own.has(name)) {
      return match;
    }
    const entry = mapping.scss[name];
    if (entry.keep) {
      if (entry.hint) plan.todos.push(`${match}: ${hintOf(mapping, entry)}`);
      else if (entry.note) plan.notes.push(`${match}: ${entry.note}`);
      return match;
    }
    if (entry.to) {
      plan.changes.push(`${match} → ${namespace}${entry.to}`);
      // A target that keeps its name with a note of its own (a stacking rank) says it here, once.
      const note = entry.note ?? mapping.scss[entry.to]?.note;
      if (note) plan.notes.push(`${match} → ${namespace}${entry.to}: ${note}`);
      return `${namespace}${entry.to}`;
    }
    if (entry.value) {
      plan.changes.push(`${match} → ${entry.value}`);
      if (entry.note) plan.notes.push(`${match} → ${entry.value}: ${entry.note}`);
      return entry.value;
    }
    plan.todos.push(`${match}: ${hintOf(mapping, entry)}`);
    return match;
  });
}

/*
 * The SCSS variables of `@ovhcloud/ods-themes` (read through its namespace): the palette by its
 * own table (`scssPalette`), any other one as the CSS custom property of the same name, resolved
 * from the property like a var() → `var(<v20>)`.
 */
function migrateThemeVariables(mapping, text, node, context, plan, atRule) {
  const root = node.root();
  if (!readsThemes(root)) {
    return text;
  }
  const themes = themesOf(root);
  const own = variablesOf(root);
  const numbers = new Set(mapping.scssNumberToVar ?? []);
  const edits = [];
  for (const match of text.matchAll(THEME_VARIABLE)) {
    const [whole, namespace, bare] = match;
    const name = `$${bare}`;
    if ((namespace ? !themes.namespaces.has(namespace) : (!themes.bare || own.has(name))) || name in (mapping.scss ?? {}) || numbers.has(name)) {
      continue;
    }
    const palette = mapping.scssPalette?.[name];
    let result;
    if (palette) {
      result = palette.value
        ? { note: palette.note ? `${whole} → ${palette.value}: ${palette.note}` : null, to: palette.value }
        : { todo: `${whole}: ${hintOf(mapping, palette)}` };
    } else if (mapping.tokens[`--${bare}`]) {
      const css = resolveToken(mapping, `--${bare}`, context);
      result = { note: css.note, todo: css.todo && `${whole} (${css.todo})`, to: css.to && `var(${css.to})` };
    } else {
      continue;
    }
    if (result.to && sassComputes(text, match.index, atRule)) {
      plan.todos.push(`${whole}: a CSS custom property in v20 (${result.to}), which Sass cannot compute with here: write the value, or move the computation to CSS`);
      continue;
    }
    if (result.todo) plan.todos.push(result.todo);
    if (result.note) plan.notes.push(result.note);
    if (result.to) {
      // A Sass number of v19 that is a var() in v20, next to an operator or a unary minus: moved into a calc().
      const arithmetic = /^var\(/.test(result.to) && arithmeticAround(text, match.index, match.index + whole.length);
      if (arithmetic?.todo) {
        plan.todos.push(`${whole}: a CSS custom property in v20 (${result.to}), not a Sass number: Sass cannot compute with it, write calc(${result.to} …) or a value of yours`);
        continue;
      }
      const edit = arithmetic ? arithmetic.edit(result.to) : { end: match.index + whole.length, start: match.index, text: result.to };
      plan.changes.push(`${text.slice(edit.start, edit.end)} → ${edit.text}`);
      edits.push(edit);
    }
  }
  return applyEdits(text, edits);
}

/*
 * The Sass arithmetic around `text[start, end)`, which a var() cannot take: a unary minus, or one
 * `+`, `-` or `*` with its operand (moved into a calc()); `/`, `%` and comparisons are marked
 * (`todo`). Null when the name stands alone.
 */
function arithmeticAround(text, start, end) {
  const minus = text.slice(0, start).match(/(?:^|[\s,:(])(-|-\(\s*)$/);
  const closing = minus?.[1].includes('(') ? text.slice(end).match(/^\s*\)/) : [''];
  if (minus && closing) {
    const from = start - minus[1].length;
    return { edit: (to) => ({ end: end + closing[0].length, start: from, text: `calc(-1 * ${to})` }) };
  }
  const right = text.slice(end).match(/^\s*([*/+%]|==|!=|<=|>=|<|>)\s*|^\s+(-)\s+/);
  const left = text.slice(0, start).match(/\s*([*/+%]|==|!=|<=|>=|<|>)\s*$|\s(-)\s+$/);
  if (!right && !left) return null;
  const operator = (right && (right[1] ?? right[2])) || (left && (left[1] ?? left[2]));
  if (!/^[-+*]$/.test(operator)) return { todo: true };
  if (right) {
    const operand = text.slice(end + right[0].length).match(/^(\([^()]*\)|[^\s;,)]+)/);
    if (!operand) return { todo: true };
    const stop = end + right[0].length + operand[0].length;
    return { edit: (to) => ({ end: stop, start, text: `calc(${to} ${operator} ${operand[0]})` }) };
  }
  const operand = text.slice(0, start - left[0].length).match(/(\([^()]*\)|[^\s(,:]+)$/);
  if (!operand) return { todo: true };
  const from = start - left[0].length - operand[0].length;
  return { edit: (to) => ({ end, start: from, text: `calc(${operand[0]} ${operator} ${to})` }) };
}

/*
 * A Sass number of ods-react that is a var() in v20 (`scssNumberToVar`): `+`, `-` and `*` move
 * into a calc(), what Sass alone can compute (`/`, `math.*`, comparisons) is marked.
 */
function migrateNumbers(mapping, text, own, plan, atRule) {
  const edits = [];
  for (const match of text.matchAll(patternsOf(mapping).number)) {
    const [whole, namespace, bare] = match;
    const start = match.index;
    const end = start + whole.length;
    if ((!namespace && own.has(`$${bare}`)) || edits.some((item) => start < item.end && end > item.start)) {
      continue;
    }
    const calls = openCalls(text.slice(0, start));
    if (calls.some((name) => name === '#{' || MATH.test(name))) {
      continue;
    }
    // A unary minus (`-$x`, `-ns.$x`, `-($x)`): Sass would emit `-var(…)`, a value the browser drops.
    const minus = text.slice(0, start).match(/(?:^|[\s,:(])(-|-\(\s*)$/);
    const closing = minus?.[1].includes('(') ? text.slice(end).match(/^\s*\)/) : [''];
    if (minus && closing && !calls.slice(minus[1].includes('(') ? 1 : 0).some((name) => SASS_FUNCTION.test(name)) && !SASS_CONTROL.test(atRule ?? '')) {
      const from = start - minus[1].length;
      const stop = end + closing[0].length;
      const replacement = `calc(-1 * #{${whole}})`;
      edits.push({ end: stop, start: from, text: replacement });
      plan.changes.push(`${text.slice(from, stop)} → ${replacement}`);
      continue;
    }
    const right = text.slice(end).match(/^\s*([*/+%]|==|!=|<=|>=|<|>)\s*|^\s+(-)\s+/);
    const left = text.slice(0, start).match(/\s*([*/+%]|==|!=|<=|>=|<|>)\s*$|\s(-)\s+$/);
    const sassOnly = calls.some((name) => SASS_FUNCTION.test(name));
    if (!right && !left && !sassOnly && !SASS_CONTROL.test(atRule ?? '')) {
      continue;
    }
    const operator = (right && (right[1] ?? right[2])) || (left && (left[1] ?? left[2]));
    if (sassOnly || SASS_CONTROL.test(atRule ?? '') || !/^[-+*]$/.test(operator ?? '') || bare === 'ods-link-font-weight') {
      plan.todos.push(`${whole}: a CSS custom property (var()) in v20, not a Sass number: Sass cannot compute with it, write calc(#{${whole}} …) or a value of yours`);
      continue;
    }
    if (right) {
      const operand = text.slice(end + right[0].length).match(/^(\([^()]*\)|[^\s;,)]+)/);
      if (!operand) continue;
      const stop = end + right[0].length + operand[0].length;
      const replacement = `calc(#{${whole}} ${operator} ${operand[0]})`;
      edits.push({ end: stop, start, text: replacement });
      plan.changes.push(`${text.slice(start, stop)} → ${replacement}`);
    } else {
      const operand = text.slice(0, start - left[0].length).match(/(\([^()]*\)|[^\s(,:]+)$/);
      if (!operand) continue;
      const from = start - left[0].length - operand[0].length;
      const replacement = `calc(${operand[0]} ${operator} #{${whole}})`;
      edits.push({ end, start: from, text: replacement });
      plan.changes.push(`${text.slice(from, end)} → ${replacement}`);
    }
  }
  return applyEdits(text, edits);
}

/* Every SCSS variable pass, on a value or on at-rule params. */
function migrateScss(mapping, text, node, context, plan, atRule) {
  const { hasNumber, hasScss } = patternsOf(mapping);
  const own = variablesOf(node.root());
  let output = text;
  if (hasScss.test(output)) output = migrateVariables(mapping, output, own, plan);
  if (/\$ods-/.test(output)) output = migrateThemeVariables(mapping, output, node, context, plan, atRule);
  if (hasNumber.test(output)) output = migrateNumbers(mapping, output, own, plan, atRule);
  return output;
}

/*
 * The declarations of each scope that declare the same v20 name from different v19 names
 * (`--ods-theme-text-color` and `--ods-theme-input-text-color` both become `content-text`): the
 * scope is the rule, and the whole file for the rules on the document root. Computed once per
 * stylesheet, before any rewrite, so the codemod and the stylelint fix read the same.
 */
const collisions = new WeakMap();
function collisionsOf(root, mapping) {
  if (!collisions.has(root)) {
    const scopes = new Map();
    root.walkDecls(/^--ods-/, (decl) => {
      const to = declaredTarget(mapping, decl.prop);
      if (!to || (decl.prop in mapping.tokens && selfReference(mapping, decl.value, to))) {
        return;
      }
      const rule = decl.parent;
      const scope = rule.type === 'root' || (rule.type === 'rule' && stateOf(decl).root === 'all') ? root : rule;
      if (!scopes.has(scope)) scopes.set(scope, new Map());
      const byTarget = scopes.get(scope);
      if (!byTarget.has(to)) byTarget.set(to, []);
      byTarget.get(to).push({ name: decl.prop, node: decl });
    });
    collisions.set(root, scopes);
  }
  return collisions.get(root);
}

/* The other v19 name an earlier declaration of the same scope turns into the same v20 name, if any. */
function collisionOf(node, mapping, to) {
  for (const byTarget of collisionsOf(node.root(), mapping).values()) {
    const list = byTarget.get(to) ?? [];
    const index = list.findIndex((item) => item.node === node);
    if (index > 0) {
      return list.slice(0, index).find((item) => item.name !== node.prop)?.name ?? null;
    }
  }
  return null;
}

const isStyleMarked = (node) => node.prev()?.type === 'comment' && node.prev().text.startsWith(TODO);

/* The messages of an earlier marker on a v20 declaration that still holds (`both become`): the rule keeps reporting them. */
function markedCollisions(node) {
  if (!isStyleMarked(node)) {
    return [];
  }
  return node.prev().text.slice(TODO.length + 2).split(/ \/ (?=--ods-)/).filter((message) => message.includes(` both become ${node.prop} in v20`));
}

/* Where a width set on a control part moves in v20 (#1121), or null. */
/* The ODS overlay parts a stylesheet can stack (`[data-ods="drawer-content"]`, `[data-scope="popover"][data-part="positioner"]`). */
const OVERLAY_PART = /\[\s*data-ods\s*=\s*['"]?(?:[a-z-]+-(?:content|positioner|backdrop)|toaster|drawer|modal)['"]?\s*\]|\[\s*data-scope\s*=[^\]]+\]\s*\[\s*data-part\s*=\s*['"]?(?:positioner|content|backdrop)/;
/* The links whose underline is a ::after shown at rest in v20 (Link underline section of the migration guide). */
const LINK_PART = /\[\s*data-ods\s*=\s*['"]?(?:link|breadcrumb-link)['"]?\s*\]/;
/* The parts that render an information Tag in v19 and an accent one in v20 (the Combobox and Query Filter tags). */
const ACCENT_TAG_HOST = /\[\s*data-ods\s*=\s*['"]?(?:combobox|combobox-control|query-filter|query-filter-tags)['"]?\s*\]/;

/*
 * What a rule that styles an ODS part does that v20 changes without renaming anything: a z-index
 * on an overlay (re-ranked), the ::after of a link (now shown at rest), an information Tag token
 * aimed at the Combobox or Query Filter tags (now accent).
 */
function partChecks(node, mapping) {
  if (node.type !== 'decl') return null;
  const chain = chainOf(node);
  const selector = chain.join(' ');
  if (!selector) return null;
  // A place the integrator decided (`/* ods-v20: checked */` right before it): nothing to add.
  if (node.prev()?.type === 'comment' && isChecked(`/*${node.prev().raws.left ?? ' '}${node.prev().text}${node.prev().raws.right ?? ' '}*/`)) return null;
  if (node.prop === 'z-index' && OVERLAY_PART.test(selector) && /^\s*-?\d+\s*(!important)?\s*$/.test(node.value) && stackingNeedsCheck(node.value.replace(/!important/, ''))) {
    return { todo: `z-index: ${node.value.trim()} on an ODS overlay: the ODS overlays get new z-index values in v20 (v19: dropdowns 99, modal 100, drawer 101; v20: sticky 100, dropdowns 200, drawer 300, modal 400) and a drawer now sits under a modal: keep or change this value so the element sits where it must. Once decided, put a comment \`ods-v20: checked\` right before it, so that ods-migrate and --check leave it.` };
  }
  const linkAfter = (LINK_PART.test(selector) || node.parent?.nodes?.some((sibling) => sibling.type === 'atrule' && /ods-link\s*\(/.test(sibling.params))) && /::?after/.test(selector);
  if (linkAfter && /^(height|transform|display|transition)$/.test(node.prop)) {
    return { todo: `${node.prop} on the ::after of a link: the link underline is this ::after in v20, shown at rest (1px) and 2px on hover. Set \`--ods-link-underline-thickness\` / \`--ods-link-underline-thickness-hover\` on the link or its container instead. Once decided, put a comment \`ods-v20: checked\` right before it, so that ods-migrate and --check leave it.` };
  }
  if (LINK_PART.test(selector) && !/::?after/.test(selector) && node.prop === 'text-decoration' && /\bnone\b/.test(node.value)) {
    return { todo: 'text-decoration: none on a link: the v20 underline is a ::after shown at rest, which this does not remove. To keep links without an underline at rest, set `--ods-link-underline-thickness: 0` on them or on their container. Once decided, put a comment \`ods-v20: checked\` right before it, so that ods-migrate and --check leave it.' };
  }
  const tag = node.prop.match(/^--ods-tag-([a-z-]+)-color-information(-hover|-active)?$/);
  if (tag && ACCENT_TAG_HOST.test(selector)) {
    const to = `--ods-tag-${tag[1]}-color-accent${tag[2] ?? ''}`;
    return mapping.tokens[node.prop] ? null : { note: `${node.prop} → ${to}: the Combobox and Query Filter tags are accent in v20, information in v19`, to };
  }
  return null;
}

function controlOf(node) {
  if (node.type !== 'decl' || !WIDTH.test(node.prop)) {
    return null;
  }
  const chain = chainOf(node);
  const match = chain.length ? selectorList(chain.at(-1)).map((complex) => subjectOf(complex).match(CONTROL)).find(Boolean) : null;
  return match ? { message: `the field width lives on the root in v20 (#1121): set it on ${CONTROL_ROOTS[match[2]]}`, part: match[2] } : null;
}

/* `--color-ods-color-primary-500` declared in a Tailwind v4 `@theme`: the key, its v20 name and the new property. */
function tailwindThemeKey(node, mapping) {
  if (node.type !== 'decl' || node.parent?.type !== 'atrule' || node.parent.name !== 'theme') {
    return null;
  }
  const namespace = node.prop.match(THEME_NAMESPACE)?.[0];
  const key = namespace && node.prop.slice(namespace.length);
  const to = key && Object.hasOwn(mapping.tailwindKeys ?? {}, key) ? mapping.tailwindKeys[key] : null;
  return to ? { from: key, prop: `${namespace}${to}`, to } : null;
}

/*
 * The Tailwind keys a utility may follow: the ones whose theme definition the run renames
 * (`options.tailwindKeys`, collected by the CLI over every file), and the ones the stylesheet
 * itself declares in its `@theme`.
 */
const themeKeySets = new WeakMap();
function themeKeysOf(root, mapping, options) {
  if (!themeKeySets.has(root)) {
    const keys = new Set(options.tailwindKeys ?? []);
    root.walkDecls((decl) => {
      const key = tailwindThemeKey(decl, mapping);
      if (key) keys.add(key.from);
    });
    themeKeySets.set(root, keys);
  }
  return themeKeySets.get(root);
}

/*
 * `theme('borderRadius.ods-border-radius-md')` (Tailwind v3): the path follows its key, renamed
 * where the run renames the key's definition, marked otherwise (a build error in v3 once renamed).
 */
function migrateThemePaths(mapping, value, themeKeys, plan) {
  return value.replace(/\btheme\(\s*(['"]?)([A-Za-z]+)\.([\w-]+)\1\s*\)/g, (whole, quote, section, key) => {
    if (!Object.hasOwn(mapping.tailwindKeys ?? {}, key)) return whole;
    const to = mapping.tailwindKeys[key];
    if (to && themeKeys?.has(key)) {
      plan.changes.push(`theme(${section}.${key}) → theme(${section}.${to}) (Tailwind key)`);
      return `theme(${quote}${section}.${to}${quote})`;
    }
    plan.todos.push(to
      ? `theme(${section}.${key}): a Tailwind key of the ODS guide, \`${to}\` in v20: rename it in your Tailwind theme and here together`
      : `theme(${section}.${key}): a Tailwind key of the ODS v19 guide with no v20 name: rename it in your Tailwind theme and here together`);
    return whole;
  });
}

function planDeclaration(node, mapping, options) {
  const { hasNumber, hasScss, hasTailwindKey, hasToken } = patternsOf(mapping);
  const themePath = /\btheme\(/.test(node.value) && hasTailwindKey.test(node.value);
  const control = controlOf(node);
  const part = partChecks(node, mapping);
  const built = node.type === 'decl' ? node.prop.match(/^(--ods-[a-z0-9-]*?)-?#\{/) : null;
  const themed = /\$ods-/.test(node.value) && readsThemes(node.root());
  const sticky = node.prop.startsWith('--ods-') && !(node.prop in mapping.tokens) ? markedCollisions(node) : [];
  const themeKey = tailwindThemeKey(node, mapping);
  if (!hasToken.test(`${node.prop} ${node.value}`) && !hasScss.test(node.value) && !HAS_OLD_FONT.test(node.value) && !hasNumber.test(node.value)
    && !DYNAMIC.test(node.value) && !/--ods-/.test(node.value.match(/(['"])[\s\S]*\1/)?.[0] ?? '') && !themed && !control && !sticky.length && !themeKey && !themePath && !part && !built) {
    return null;
  }
  if (node.prop.startsWith('--ods-')) {
    // Before the first rewrite of a declaration of the stylesheet (a stylelint fix runs in the walk).
    collisionsOf(node.root(), mapping);
  }
  const plan = { changes: [], notes: [], todos: [...sticky] };
  if (control) {
    plan.notes.push(`${node.prop} on [data-ods="${control.part}"]: ${control.message}`);
  }
  let prop = node.prop;
  if (part?.todo) plan.todos.push(part.todo);
  if (part?.to) {
    prop = part.to;
    plan.changes.push(part.note);
  }
  let declared = null;
  // A key of a Tailwind v4 theme (`@theme { --color-ods-color-primary-500: … }`): renamed with its utilities.
  if (themeKey) {
    prop = themeKey.prop;
    plan.changes.push(`${themeKey.from} → ${themeKey.to} (Tailwind key)`);
  }
  // `--ods-tag-background-color-#{$status}: …`: the name is built at compile time.
  if (built && isTokenPrefix(mapping, `${built[1]}-`)) {
    plan.todos.push(`${built[1]}-#{…}: token name built at runtime: map each value by hand`);
  }
  // An app that overrides an ODS token in its own :root: the declared name migrates too.
  if (node.prop.startsWith('--ods-') && node.prop in mapping.tokens) {
    declared = declaredName(mapping, node.prop);
    if (declared.todo) plan.todos.push(declared.todo);
    // A palette stop declared inside a container: v20 computes the roles from the palette on :root only (BC-20).
    if (declared.to?.startsWith('--ods-palette-') && stateOf(node).root !== 'all') {
      const readers = mapping.tokens[node.prop].paletteShared ?? [];
      plan.todos.push(`${node.prop} → ${declared.to} outside :root: in v20 the roles read the palette on :root only, so this declaration recolours nothing here. Declare the roles this container needs instead (\`--ods-semantic-color-*\`${readers.length ? `, e.g. ${readers.slice(0, 3).map((reader) => `\`${reader}\``).join(', ')}` : ''})`);
    }
    if (declared.note) plan.notes.push(declared.note);
    if (declared.to) prop = declared.to;
  }
  const context = { ...declarationContext(node.prop === prop || themeKey ? fullProperty(node) : prop, stateOf(node)), config: options.config, themeKeys: themeKeysOf(node.root(), mapping, options) };
  if (!context.role && /^box-shadow$/i.test(fullProperty(node)) && isRingShadow(node.value)) {
    context.role = 'border';
  }
  let value = themePath ? migrateThemePaths(mapping, node.value, context.themeKeys, plan) : node.value;
  value = migrateValue(mapping, value, context, plan);
  value = migrateScss(mapping, value, node, context, plan);
  if (declared?.to) {
    if (readsItself(value, declared.to)) {
      // `--ods-theme-input-border-width: var(--ods-theme-border-width)`: both are border-thickness in v20.
      const other = selfReference(mapping, node.value, declared.to) ?? declared.to;
      return { changes: [], notes: [], prop: node.prop, todos: [selfMessage(node.prop, other, declared.to)], value: node.value };
    }
    const other = collisionOf(node, mapping, declared.to);
    if (other) plan.todos.push(collisionMessage(node.prop, other, declared.to));
    const siblings = new Set((node.parent?.nodes ?? []).filter((sibling) => sibling.type === 'decl').map((sibling) => sibling.prop));
    const extra = declared.extra.filter((name) => !siblings.has(name));
    plan.changes.unshift(extra.length ? `${node.prop} → ${declared.to} + ${extra.join(' + ')} (v20 splits what it set)` : `${node.prop} → ${declared.to}`);
    if (extra.length) plan.extra = extra.map((name) => ({ prop: name, value }));
  }
  return { ...plan, prop, value };
}

/* The first argument of an `@include x(…)`, by position or as `$color:`: its text, and whether it is a quoted literal. */
function statusArgument(rest) {
  const match = rest.match(/^\s*\(\s*(?:\$color\s*:\s*)?(?:(['"])([a-z]+)\1|([^,)]+))/);
  if (!match) return null;
  const raw = match[1] ? `${match[1]}${match[2]}${match[1]}` : match[3].trim();
  return { index: match.index + match[0].length - (match[1] ? raw.length : match[3].length), quote: match[1], quoted: Boolean(match[1]), raw, value: match[2] ?? raw };
}

function planAtRule(node, mapping, options) {
  const { hasMixin, hasModifier, hasNumber, hasScss, hasTailwindKey, hasToken } = patternsOf(mapping);
  const { name } = node;
  const include = name === 'include' && hasMixin.test(node.params);
  const fontMixin = name === 'include' && /\bsource-sans-pro(-italic)?-font-face\b/.test(node.params);
  const apply = name === 'apply' && (hasToken.test(node.params) || hasTailwindKey.test(node.params) || hasModifier.test(node.params));
  if (!include && !fontMixin && !apply && !hasToken.test(node.params) && !hasScss.test(node.params) && !hasNumber.test(node.params)
    && !HAS_OLD_FONT.test(node.params) && !DYNAMIC.test(node.params) && !(/\$ods-/.test(node.params) && readsThemes(node.root()))) {
    return null;
  }
  const plan = { changes: [], notes: [], todos: [] };
  let { params } = node;
  if (include) {
    const [match, namespace, mixin] = params.match(patternsOf(mapping).mixin);
    const entry = mapping.mixins[mixin];
    const target = entry.to ?? mixin;
    if (entry.to) {
      params = `${namespace}${entry.to}${params.slice(match.length)}`;
      plan.changes.push(`@include ${namespace}${mixin} → ${namespace}${entry.to}`);
    }
    const status = statusArgument(params.slice(namespace.length + target.length));
    if (status?.quoted && entry.args?.[status.value]) {
      const start = namespace.length + target.length + status.index;
      params = `${params.slice(0, start)}${status.quote}${entry.args[status.value]}${status.quote}${params.slice(start + status.raw.length)}`;
      plan.changes.push(`@include ${target}('${status.value}') → ('${entry.args[status.value]}')`);
    } else if (status?.quoted && entry.removedArgs?.includes(status.value)) {
      plan.todos.push(`@include ${target}('${status.value}'): v20 has no '${status.value}' ${/button/.test(target) ? 'Button' : 'status'}: the build stops on it. Use 'neutral', or style the element yourself.`);
    } else if (status && !status.quoted && (entry.args || entry.removedArgs)) {
      plan.todos.push(`@include ${target}(${status.raw}): a status passed through a variable: v20 renamed ${Object.entries(entry.args ?? {}).map(([from, to]) => `'${from}' to '${to}'`).join(', ')}${entry.removedArgs ? ` and removed ${entry.removedArgs.map((value) => `'${value}'`).join(', ')}` : ''}, and stops the build on any value it does not know: check every value it can hold.`);
    }
    if (entry.hint) plan.todos.push(`@include ${mixin}(): ${hintOf(mapping, entry)}`);
    if (entry.note) plan.notes.push(`@include ${mixin}(): ${entry.note}`);
  }
  if (fontMixin) {
    params = params.replace(OLD_FONT_MIXIN, (match, italic = '') => {
      plan.changes.push(`source-sans-pro${italic}-font-face → source-sans-3${italic}-font-face`);
      return `source-sans-3${italic}-font-face`;
    });
  }
  if (apply) {
    // Tailwind classes: the utility and its variants give the role, as in a script.
    const text = planText(mapping, params, { config: options.config, css: false, hashed: false, themeKeys: themeKeysOf(node.root(), mapping, options) });
    params = applyEdits(params, text.edits);
    text.edits.forEach((item) => plan.changes.push(item.message));
    plan.todos.push(...text.todos);
    plan.notes.push(...text.notes);
  } else if (hasToken.test(params) || DYNAMIC.test(params)) {
    // Mixin arguments, @use / @import paths, `with (…)` configurations: no property to read a role from.
    params = migrateValue(mapping, params, { config: options.config, role: null }, plan);
  } else {
    params = renameFont(params, plan, options.config);
  }
  params = migrateScss(mapping, params, node, { config: options.config, role: null }, plan, name);
  return { ...plan, params };
}

/* A selector that reads an internal class of a component (`cssModifiers`). */
function planRule(node, mapping, options) {
  const { hasModifier, modifier } = patternsOf(mapping);
  if (isNestedProperty(node) || !hasModifier.test(node.selector)) {
    return null;
  }
  const plan = { changes: [], notes: [], todos: [] };
  const edits = [];
  for (const match of node.selector.matchAll(modifier)) {
    for (const item of planModifier(mapping, node.selector, match, false, options.config)) {
      if (item.todo) plan.todos.push(item.todo);
      else if (item.note) plan.notes.push(item.note);
      else {
        edits.push(item);
        plan.changes.push(item.message);
      }
    }
  }
  return plan.changes.length || plan.todos.length ? { ...plan, selector: applyEdits(node.selector, edits) } : null;
}

/**
 * What the migration does to one declaration, at-rule or rule, without touching it: the codemod
 * applies it, the stylelint rule reports it and applies it as its fix. Null when there is nothing to do.
 */
function planStyleNode(node, rawMapping, options = {}) {
  const mapping = resolveTokenMapping(rawMapping, options.config);
  if (node.type === 'decl') return planDeclaration(node, mapping, options);
  if (node.type === 'atrule') return planAtRule(node, mapping, options);
  if (node.type === 'rule') return planRule(node, mapping, options);
  return null;
}

function applyStylePlan(node, plan) {
  if (node.type === 'decl') {
    if (plan.prop !== node.prop) node.prop = plan.prop;
    if (plan.value !== node.value) node.value = plan.value;
    for (const extra of [...(plan.extra ?? [])].reverse()) {
      node.cloneAfter({ prop: extra.prop, value: extra.value });
    }
  } else if (node.type === 'rule') {
    if (plan.selector !== undefined && plan.selector !== node.selector) node.selector = plan.selector;
  } else if (plan.params !== node.params) {
    node.params = plan.params;
  }
}

/**
 * Migrates a stylesheet. Declarations are rewritten in place, so the file keeps its formatting;
 * what cannot be migrated gets a `/* TODO(ods-v20) … *\/` comment before its declaration.
 * `options.markers: false` turns the todos into notes (HTML, which takes no marker).
 */
function transformStyles(source, rawMapping, filename = 'file.css', options = {}) {
  const mapping = resolveTokenMapping(rawMapping, options.config);
  const report = createReport();
  if (!hasWork(source, mapping) || isGeneratedOptOut(source)) {
    return { output: source, ...report };
  }
  const syntax = /\.scss$/.test(filename) ? scss : postcss;
  const root = syntax.parse(source, { from: filename });
  collisionsOf(root, mapping);

  root.walk((node) => {
    const plan = planStyleNode(node, mapping, options);
    if (!plan) {
      return;
    }
    const line = node.source.start.line;
    plan.changes.forEach((message) => report.changes.push({ line, message }));
    plan.notes.forEach((message) => report.notes.push({ line, message }));
    applyStylePlan(node, plan);
    if (plan.todos.length && options.markers === false) {
      plan.todos.forEach((message) => report.notes.push({ line, message }));
    } else if (plan.todos.length && !isStyleMarked(node)) {
      // Explicit raws: postcss would copy the style of the other comments of the file (`/*\n …\n */`).
      node.before(postcss.comment({ raws: { left: ' ', right: ' ' }, text: styleMarker(plan.todos) }));
      plan.todos.forEach((message) => report.todos.push({ line, message }));
    }
  });

  const output = root.toString(syntax === scss ? scss.stringify : undefined);
  return { output, ...sortReport(report) };
}

/** True for the opt-out CSS that the CLI generates from the config: it holds the v19 look on purpose. */
const isGeneratedOptOut = (source) => source.replace(/^\uFEFF/, '').startsWith(OPT_OUT_HEADER);

/* ---------------------------------------------------------------- TypeScript and JavaScript */

function langFor(filename) {
  return /\.(c|m)?ts$/.test(filename) ? Lang.TypeScript : Lang.Tsx;
}

const kebab = (key) => key.replace(/^['"]|['"]$/g, '').replace(/[A-Z]/g, (char) => `-${char.toLowerCase()}`);
const unquote = (text) => text.replace(/^(['"`])([\s\S]*)\1$/, '$2');
const WRAPPERS = new Set(['parenthesized_expression', 'as_expression', 'satisfies_expression', 'ternary_expression', 'binary_expression', 'jsx_expression']);

/*
 * The pair or JSX attribute a string is the value of, through what keeps its role: a ternary
 * branch, `||` / `??` / `&&`, parentheses, `as` / `satisfies`.
 */
function ownerOf(stringNode) {
  let child = stringNode;
  for (let parent = child.parent(); parent; child = parent, parent = parent.parent()) {
    const kind = parent.kind();
    if (kind === 'pair' || kind === 'jsx_attribute') {
      return parent;
    }
    if (!WRAPPERS.has(kind)) {
      return null;
    }
    if (kind === 'ternary_expression' && parent.field('condition')?.range().start.index === child.range().start.index) {
      return null;
    }
    if (kind === 'binary_expression' && !/^(\|\||\?\?|&&)$/.test(parent.field('operator')?.text() ?? '')) {
      return null;
    }
  }
  return null;
}

/* The selector keys around a style object (`'&:hover': { … }`), outermost first. */
function keyChain(pair) {
  const chain = [];
  for (let node = pair.parent(); node; node = node.parent()) {
    if (node.kind() === 'pair') {
      const key = unquote(node.field('key')?.text() ?? '');
      if (/[&:]/.test(key)) chain.unshift(key);
    }
    // `<body style={ { … } }>`: the document root, as `body { … }` would be.
    if (node.kind() === 'jsx_attribute' && node.child(0)?.text() === 'style') {
      const tag = node.parent()?.field('name')?.text();
      if (tag === 'html' || tag === 'body') chain.unshift(tag);
      break;
    }
  }
  return chain;
}

function keyChainHas(pair, name) {
  for (let node = pair.parent(); node; node = node.parent()) {
    if (node.kind() === 'pair' && unquote(node.field('key')?.text() ?? '') === name) return true;
  }
  return false;
}

function lineIndex(source) {
  const starts = [0];
  for (let i = source.indexOf('\n'); i >= 0; i = source.indexOf('\n', i + 1)) starts.push(i + 1);
  return (index) => {
    let low = 0;
    let high = starts.length - 1;
    while (low < high) {
      const middle = (low + high + 1) >> 1;
      if (starts[middle] <= index) low = middle;
      else high = middle - 1;
    }
    return low + 1;
  };
}

/**
 * What the migration does to the tokens written in strings (Tailwind classes, style objects,
 * CSS-in-JS templates, Tailwind configs), as character ranges: the codemod applies it, the
 * ESLint rule reports it and fixes with it. The role comes from the string itself or the key it
 * is the value of, never from a neighbouring line.
 */
function planScriptTokens(source, rawMapping, filename = 'file.tsx', options = {}) {
  const mapping = resolveTokenMapping(rawMapping, options.config);
  const plan = { edits: [], markers: [], notes: [] };
  const tailwindConfig = Object.keys(mapping.tailwindKeys ?? {}).some((key) => source.includes(key));
  if (!hasWork(source, mapping) && !tailwindConfig) {
    plan.markers = markedScriptCollisions(source);
    return plan;
  }
  const root = parse(langFor(filename), source).root();
  const lineOf = lineIndex(source);
  const markers = new Map();
  const done = new Set();
  const { config } = options;

  /* Where a marker goes: before the attribute, the object property, or the string itself. */
  const mark = (stringNode, message) => {
    const anchor = ownerOf(stringNode) ?? stringNode;
    const { index } = anchor.range().start;
    if (!markers.has(index)) {
      // The lint report starts at the anchor, so it sits on the line of the marker even when the string is further down.
      markers.set(index, { end: stringNode.range().end.index, index, line: lineOf(index), marked: followsMarker(source, index), messages: [], start: index });
    }
    if (!markers.get(index).messages.includes(message)) markers.get(index).messages.push(message);
  };
  const seen = new Set();
  const edit = (start, end, text, message) => {
    if (seen.has(`${start}:${end}`)) return;
    seen.add(`${start}:${end}`);
    plan.edits.push({ end, line: lineOf(start), message, start, text });
  };
  const note = (index, message) => plan.notes.push({ line: lineOf(index), message });

  // A Tailwind theme (a tailwind.config, a preset): its keys are renamed to the documented v20 names
  // (`tailwindKeys`), and the utilities that follow them, in this file or in the run (`options.tailwindKeys`).
  const themeKeys = new Set(options.tailwindKeys ?? []);
  for (const { inner, key, name, to } of tailwindThemePairs(root, mapping)) {
    // A key of the v19 guide with no v20 name: its utilities are marked where they are used, its definition here.
    if (!to) {
      mark(key, noTailwindKey(name));
      continue;
    }
    themeKeys.add(name);
    edit(inner.range().start.index, inner.range().end.index, inner.parent()?.kind() === 'string' || /^[A-Za-z_$][\w$]*$/.test(to) ? to : `'${to}'`, `${name} → ${to} (Tailwind key)`);
  }

  // A regex of the config (a `safelist` pattern) that names a renamed key: a regex is not rewritten.
  for (const regex of themeKeys.size ? root.findAll({ rule: { kind: 'regex' } }) : []) {
    // A key, or its stem followed by a group (`ods-border-radius-(sm|md)`).
    const keys = [...themeKeys].filter((key) => mapping.tailwindKeys[key] && (regex.text().includes(key) || regex.text().includes(`${key.replace(/[^-]+$/, '')}(`)));
    if (keys.length) note(regex.range().start.index, `${regex.text()}: names the Tailwind key${keys.length > 1 ? 's' : ''} ${keys.map((key) => `${key} (\`${mapping.tailwindKeys[key]}\` in v20)`).join(', ')}: rename ${keys.length > 1 ? 'them' : 'it'} in this pattern too, or the classes it keeps are dropped`);
  }

  // Object keys that declare an ODS token: `{ '--ods-theme-x': 'value' }` is a theme, as in CSS.
  for (const pair of root.findAll({ rule: { kind: 'pair' } })) {
    const key = pair.field('key');
    const name = unquote(key?.text() ?? '');
    if (!key || !/^['"]/.test(key.text()) || !(name in mapping.tokens)) {
      continue;
    }
    const value = pair.field('value');
    const fragment = value?.kind() === 'string' ? value.find({ rule: { kind: 'string_fragment' } }) : null;
    const siblings = pair.parent().children().filter((child) => child.kind() === 'pair' && child.range().start.index < pair.range().start.index)
      .map((child) => unquote(child.field('key')?.text() ?? ''));
    const declaration = planDeclarationText(mapping, name, fragment?.text() ?? '', { config, siblings });
    const keyFragment = key.find({ rule: { kind: 'string_fragment' } });
    declaration.todos.forEach((message) => mark(key, message));
    declaration.notes.forEach((message) => note(key.range().start.index, message));
    done.add(keyFragment?.range().start.index);
    if (fragment) {
      done.add(fragment.range().start.index);
      const base = fragment.range().start.index;
      declaration.edits.forEach((item) => edit(base + item.start, base + item.end, item.text, item.message));
    }
    if (!declaration.to) {
      continue;
    }
    edit(keyFragment.range().start.index, keyFragment.range().end.index, declaration.to, declaration.message);
    if (declaration.extra.length && (fragment || value?.kind() === 'number')) {
      const quote = key.text()[0];
      const migrated = fragment ? `${value.text()[0]}${applyEdits(fragment.text(), declaration.edits)}${value.text()[0]}` : value.text();
      const end = pair.range().end.index;
      edit(end, end, declaration.extra.map((prop) => `, ${quote}${prop}${quote}: ${migrated}`).join(''), declaration.message);
    }
  }

  for (const fragment of root.findAll({ rule: { kind: 'string_fragment' } })) {
    const base = fragment.range().start.index;
    if (done.has(base)) {
      continue;
    }
    const text = fragment.text();
    const stringNode = fragment.parent();
    const template = stringNode.kind() === 'template_string';
    const container = stringNode.parent();
    const dynamicTail = (template && fragment.next()?.kind() === 'template_substitution')
      || (container?.kind() === 'binary_expression' && container.field('operator')?.text() === '+' && container.field('left')?.range().start.index === stringNode.range().start.index);
    if (!hasWork(text, mapping) && !(dynamicTail && /--ods-[a-z0-9-]*$/.test(text))) {
      continue;
    }
    const owner = ownerOf(stringNode);
    const key = owner?.kind() === 'pair' ? owner.field('key') : null;
    const isKey = key && key.range().start.index === stringNode.range().start.index;
    const keyContext = key && !isKey ? declarationContext(kebab(key.text()), summarize(selectorStates(keyChain(owner)))) : null;
    // The text of the same template before this fragment (its substitutions as a placeholder).
    const before = template
      ? stringNode.children().filter((child) => child.kind() === 'string_fragment' && child.range().start.index < base).map((child) => child.text()).join('_')
      : '';
    const result = planText(mapping, text, { before, config, dynamicTail, fragment: !template, keyContext, themeKeys });
    result.edits.forEach((item) => edit(base + item.start, base + item.end, item.text, item.message));
    result.todos.forEach((message) => mark(stringNode, message));
    result.notes.forEach((message) => note(base, message));
  }

  for (const marker of markedScriptCollisions(source)) {
    if (!markers.has(marker.index)) markers.set(marker.index, marker);
  }
  plan.markers = [...markers.values()].sort((a, b) => a.index - b.index);
  return plan;
}

/* The keys of a Tailwind theme in a script (`theme: { extend: { colors: { 'ods-color-primary-500': … } } }`) that v20 renames. */
function tailwindThemePairs(root, mapping) {
  const pairs = [];
  for (const pair of root.findAll({ rule: { kind: 'pair' } })) {
    const key = pair.field('key');
    const name = unquote(key?.text() ?? '');
    if (!Object.hasOwn(mapping.tailwindKeys ?? {}, name)) continue;
    const to = mapping.tailwindKeys[name];
    const inner = key?.kind() === 'string' ? key.find({ rule: { kind: 'string_fragment' } }) : key;
    if (inner && keyChainHas(pair, 'theme')) pairs.push({ inner, key, name, to });
  }
  return pairs;
}

/**
 * The Tailwind keys of the ODS guide that a file defines in a theme (a script under a `theme`
 * key, a stylesheet in `@theme`): the CLI collects them over the run, so that a utility is renamed
 * only when its definition is renamed too.
 */
function tailwindThemeKeys(source, rawMapping, filename = 'file.tsx') {
  const mapping = resolveTokenMapping(rawMapping);
  const keys = Object.keys(mapping.tailwindKeys ?? {});
  if (!keys.some((key) => source.includes(key))) {
    return new Set();
  }
  if (/\.s?css$/.test(filename)) {
    const root = (/\.scss$/.test(filename) ? scss : postcss).parse(source, { from: filename });
    return themeKeysOf(root, mapping, {});
  }
  if (!/\.(c|m)?[jt]sx?$/.test(filename)) {
    return new Set();
  }
  return new Set(tailwindThemePairs(parse(langFor(filename), source).root(), mapping).filter(({ to }) => to).map(({ name }) => name));
}

/*
 * The collision markers of an earlier run (`X and Y both become Z in v20: keep one value`) on a
 * declaration that is v20 already: nothing is left to rewrite there, but the duplicate holds
 * until someone keeps one value, so the lint rule keeps reporting it, as in a stylesheet.
 */
function markedScriptCollisions(source) {
  if (!source.includes(' both become ')) {
    return [];
  }
  const lineOf = lineIndex(source);
  const found = [];
  for (const match of source.matchAll(/\/\* TODO\(ods-v20\): ([\s\S]*?) \*\/ /g)) {
    const index = match.index + match[0].length;
    const next = source.slice(index, source.indexOf('\n', index) < 0 ? source.length : source.indexOf('\n', index));
    // The marked node: a pair on its line, or a CSS template that may span a few lines.
    const node = source.slice(index, index + 2000).split(/\/\* TODO\(ods-v20\)/)[0];
    const messages = match[1].split(/ \/ (?=--ods-)/).filter((message) => {
      const target = message.match(/ both become (--ods-[\w-]+) in v20: keep one value$/)?.[1];
      return target && node.includes(target);
    });
    if (messages.length) {
      found.push({ end: index + next.length, index, line: lineOf(index), marked: true, messages, start: index });
    }
  }
  return found;
}

/** How many v19 names a test snapshot holds, by kind: known tokens, internal classes, names ODS v19 never declared. */
function snapshotCounts(source, rawMapping) {
  const mapping = resolveTokenMapping(rawMapping);
  const { modifier, scss, token } = patternsOf(mapping);
  const counts = { classes: 0, tokens: 0, unknown: 0 };
  for (const [name] of source.matchAll(token)) {
    if (name in mapping.tokens) counts.tokens++;
    else counts.unknown++;
  }
  counts.tokens += (source.match(scss)?.length ?? 0) + (source.match(OLD_FONT)?.length ?? 0);
  for (const [, , block, name] of source.matchAll(modifier)) {
    if (Object.hasOwn(mapping.cssModifiers[block], name)) counts.classes++;
  }
  return counts;
}

/** How many v19 names a file holds, for the files the codemod does not rewrite (Jest snapshots): known names only. */
function countV19Tokens(source, mapping) {
  return snapshotCounts(source, mapping).tokens;
}

/** Migrates the tokens written in strings of a script, and marks what the file does not say. */
function transformScriptTokens(source, rawMapping, filename = 'file.tsx', options = {}) {
  const report = createReport();
  const plan = planScriptTokens(source, rawMapping, filename, options);
  const edits = plan.edits.map(({ end, start, text }) => ({ end, start, text }));
  plan.edits.forEach(({ line, message }) => report.changes.push({ line, message }));
  report.notes.push(...plan.notes);
  for (const marker of plan.markers.filter(({ marked }) => !marked)) {
    edits.push({ end: marker.index, start: marker.index, text: inlineMarker(marker.messages) });
    marker.messages.forEach((message) => report.todos.push({ line: marker.line, message }));
  }
  // One pass over the edits sorted by position (a marker before the edit at the same index).
  edits.sort((a, b) => a.start - b.start || (a.end - a.start) - (b.end - b.start));
  const parts = [];
  let cursor = 0;
  for (const item of edits) {
    if (item.start < cursor) continue;
    parts.push(source.slice(cursor, item.start), item.text);
    cursor = item.end;
  }
  parts.push(source.slice(cursor));
  return { output: parts.join(''), ...sortReport(report) };
}

