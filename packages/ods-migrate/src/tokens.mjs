/*
 * The design token part of the migration (BC-01 to BC-04, BC-08, BC-12, BC-13, BC-16 of
 * BREAKING-CHANGES-V20.md).
 *
 * A v19 ramp step carries no role: `--ods-color-primary-500` becomes `surface-brand` as a
 * background, `border-brand` as a border and `content-brand` as a text. So every token is
 * resolved against what paints with it, read from the file itself: the CSS property and the
 * subject of its selector, the Tailwind utility and its variants, the key of a style object.
 * When nothing in the file says it, the token is marked with the candidates, never guessed.
 *
 * The component tokens and SCSS variables of ods-react that v20 removes are found by exact name:
 * most `--ods-<component>-*` and `$ods-*` names survive, so no prefix can tell them apart.
 *
 * CSS and scripts share one reading of a declaration (declarationContext): an app that declares
 * an ODS token is writing a theme, whose value reads the palette in v20, whether the declaration
 * sits in a stylesheet, a style object or a CSS-in-JS template.
 */

