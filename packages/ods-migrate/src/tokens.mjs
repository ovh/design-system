/*
 * What ODS reads instead, where its own styles migrated the same token in the same role to
 * another name than the table (`entry.ods`, found by the mapping build): the rewrite stays, the
 * reader is told which one ODS picked.
 */
function odsReads(mapping, entry, cell, to) {
  const reads = (entry.ods?.[cell] ?? []).filter(({ read }) => read !== to);
  if (!reads.length) {
    return null;
  }
  // The ODS stylesheets that read it, as kinds of elements an integrator recognises.
  const groups = reads.map(({ files, read }) => {
    const parts = files.map(odsPartOf);
    const kinds = [...new Set(parts.map(({ kind }) => kind))];
    const components = [...new Set(parts.map(({ component }) => component))];
    const named = kinds.filter((kind) => kind !== 'these components');
    // A kind of element an integrator recognises, with the components; a component alone by its name.
    return `\`${read}\` for ${named.length ? `${named.join(', ')} (${components.join(', ')})` : components.join(', ')}`;
  });
  return `${mapping.hints.ods} ${groups.length > 1 ? `${groups.slice(0, -1).join(', ')} and ${groups.at(-1)}` : groups[0]}: if this element is one of those, use that token instead; otherwise keep this one.`;
}

/* An ODS stylesheet (`selectContent.module.scss`) as its component and the kind of element it styles. */
const MULTI_WORD = ['phoneNumber', 'fileUpload', 'formField', 'progressBar', 'treeView', 'tileGroup', 'radioGroup', 'tabList'];
function odsPartOf(file) {
  const base = file.replace(/(\.module)?\.s?css$/, '').replace(/^_/, '');
  const head = MULTI_WORD.find((word) => base.startsWith(word)) ?? base.match(/^[a-z]+/)?.[0] ?? base;
  const component = head.replace(/([A-Z])/g, ' $1').replace(/^./, (char) => char.toUpperCase()).replace(/ (\w)/g, (_, char) => ` ${char.toLowerCase()}`);
  if (/Content$/.test(base) || /^(modal|drawer|dialog|popover|tooltip|menu)/.test(base)) return { component, kind: 'popups and overlays' };
  if (/Control$/.test(base) || /^(input|textarea|checkbox|radio|switch|toggle|quantity|password|phoneNumber|fileUpload|range|formField|select|combobox|datepicker|timepicker)/.test(base)) {
    return { component, kind: 'form fields' };
  }
  return { component, kind: 'these components' };
}

