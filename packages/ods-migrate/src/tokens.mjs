/*
 * The names a mapping looks for: the v19 theme families by prefix, the removed component tokens
 * and SCSS variables by exact name. A SCSS variable may come with its module namespace
 * (`ods.$ods-modal-margin`). Non-global copies are for presence tests: a global regex keeps its
 * lastIndex between calls.
 */
function patternsOf(mapping) {
  if (!patterns.has(mapping)) {
    const named = Object.keys(mapping.tokens).filter((name) => !new RegExp(`^${OLD_TOKEN.source}$`).test(name));
    const token = named.length ? `${OLD_TOKEN.source}|(?:${alternation(named)})(?![a-z0-9-])` : OLD_TOKEN.source;
    const variables = Object.keys(mapping.scss ?? {}).map((name) => name.slice(1));
    const scssSource = variables.length ? `([A-Za-z_][\\w-]*\\.)?\\$(${alternation(variables)})(?![\\w-])` : '(?!)';
    const numbers = (mapping.scssNumberToVar ?? []).map((name) => name.slice(1));
    // A unary minus may stand right before it (`-$x`, `-ns.$x`): only an identifier that goes on is excluded.
    const numberSource = numbers.length ? `(?<![\\w$]|[\\w$]-)([A-Za-z_][\\w-]*\\.)?\\$(${alternation(numbers)})(?![\\w-])` : '(?!)';
    const mixins = Object.keys(mapping.mixins ?? {});
    const mixinSource = mixins.length ? `^((?:[A-Za-z_][\\w-]*\\.)?)(${alternation(mixins)})(?![\\w-])` : '(?!)';
    const blocks = Object.keys(mapping.cssModifiers ?? {});
    const modifierSource = blocks.length ? `(?<![\\w-])(_?)(${alternation(blocks)})--([a-z0-9]+)(?![a-zA-Z0-9-])` : '(?!)';
    const keys = Object.keys(mapping.tailwindKeys ?? {});
    // After a utility (`rounded-`), a theme() path (`borderRadius.`, `['`) or a v4 theme variable (`--radius-`).
    const tailwindKeySource = keys.length ? `(?<=[a-z0-9]-|[A-Za-z]\\.|\\[['"])(${alternation(keys)})(?![\\w-])` : '(?!)';
    patterns.set(mapping, {
      hasMixin: new RegExp(mixinSource),
      hasMixinName: mixins.length ? new RegExp(`@include\\s+(?:[\\w-]+\\.)?(?:${alternation(mixins)})(?![\\w-])`) : /(?!)/,
      hasModifier: new RegExp(modifierSource),
      hasNumber: new RegExp(numberSource),
      hasScss: new RegExp(scssSource),
      hasTailwindKey: new RegExp(tailwindKeySource),
      hasToken: new RegExp(token),
      mixin: new RegExp(mixinSource),
      modifier: new RegExp(modifierSource, 'g'),
      number: new RegExp(numberSource, 'g'),
      scss: new RegExp(scssSource, 'g'),
      tailwindKey: new RegExp(tailwindKeySource, 'g'),
      token: new RegExp(token, 'g'),
    });
  }
  return patterns.get(mapping);
}

