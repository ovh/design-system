/* What a CSS property paints, or null when it does not say (a shadow, a gradient, a size). */
function roleOfProperty(property) {
  const prop = property.toLowerCase();
  if (prop.startsWith('--')) {
    // A custom property of the app: only its name can tell, and only an unambiguous word counts.
    if (/(^|-)(bg|background|surface|fill)(-|$)/.test(prop)) return 'surface';
    if (/(^|-)(border|outline|ring|divider)(-|$)/.test(prop)) return 'border';
    if (/(^|-)(text|fg|foreground|ink|heading|placeholder)(-|$)/.test(prop)) return 'content';
    return null;
  }
  if (/^(background|background-color|fill)$/.test(prop)) return 'surface';
  if (/^(border|outline|column-rule)(-(top|right|bottom|left|block|inline)(-(start|end))?)?(-color)?$/.test(prop)) return 'border';
  if (/^(color|caret-color|text-decoration-color|-webkit-text-fill-color|text-emphasis-color)$/.test(prop)) return 'content';
  return null;
}

/*
 * What a property most likely paints when it does not say it outright: a ring drawn with a
 * box-shadow is a border, a gradient on `background` a background. Only a suggestion in a marker,
 * never a rewrite.
 */
function likelyRoleOfProperty(property) {
  const prop = property.toLowerCase();
  if (/^(box-shadow|stroke|outline-color)$/.test(prop)) return 'border';
  if (/^(background-image)$/.test(prop)) return 'surface';
  return roleOfProperty(prop);
}

const TAILWIND_ROLE = [
  [/^bg$/, 'surface'],
  [/^fill$/, 'surface'],
  // `accent` is left out on purpose: like the `accent-color` property, it paints a control, not a text.
  [/^(text|decoration|caret|placeholder)$/, 'content'],
  [/^(border(-[xytrblse])?|divide(-[xy])?|outline|ring|ring-offset)$/, 'border'],
];
const HOVER_VARIANT = /^(hover|active|focus|focus-visible|focus-within|group-hover|peer-hover|group-focus|peer-focus|group-active|peer-active)$/;
const HOVER_PSEUDO = /:(hover|active|focus|focus-visible)(?![\w-])/;
/* The pressed state, which v20 paints with its own `-active` role where the palette has one. */
const ACTIVE_VARIANT = /^(active|group-active|peer-active)$/;
const ACTIVE_PSEUDO = /:active(?![\w-])/;
/* The keyboard focus, whose outline v20 paints with its focus role. */
const FOCUS_PSEUDO = /:focus(?:-visible|-within)?(?![\w-])/;
const FOCUS_RING = /^outline(-color)?$/;

/* A Tailwind variant says hover: `hover`, `group-hover/card`, `[&:hover]`, `group-[:hover]`, `has-[:hover]`. */
function isHoverVariant(variant) {
  const bare = variant.replace(/\/[\w-]+$/, '');
  if (HOVER_VARIANT.test(bare)) return true;
  const arbitrary = bare.match(/^(?:(?:group|peer|has|in)-)?\[(.*)\]$/);
  return Boolean(arbitrary) && HOVER_PSEUDO.test(withoutNegations(arbitrary[1].replace(/_/g, ' ')));
}

/*
 * The Tailwind class around `offset` in a class list, when the token is the arbitrary value of
 * a utility: `bg-[--ods-color-primary-500]`, `hover:border-b-[var(--ods-color-x)]`, `hover:!bg-[…]`.
 */
function tailwindContext(text, offset) {
  let start = offset;
  while (start > 0 && !/\s/.test(text[start - 1])) start--;
  // `bg-[…]`, or the v4 shorthand `bg-(…)`; a `color:` data-type hint inside says nothing of the role.
  const bracket = Math.max(text.lastIndexOf('-[', offset), text.lastIndexOf('-(', offset));
  if (bracket < start) {
    return null;
  }
  const open = text[bracket + 1];
  const head = text.slice(start, bracket).replace(/^!/, '');
  // Variants end at the last colon that is outside a bracket: `[&>svg]:hover:fill`.
  let depth = 0;
  let split = -1;
  for (let i = 0; i < head.length; i++) {
    if (head[i] === '[') depth++;
    else if (head[i] === ']') depth--;
    else if (head[i] === ':' && depth === 0) split = i;
  }
  const utility = head.slice(split + 1).replace(/^!|!$/g, '');
  const variants = split < 0 ? [] : splitTopLevel(head.slice(0, split), (char) => char === ':');
  let role = TAILWIND_ROLE.find(([pattern]) => pattern.test(utility))?.[1] ?? null;
  if (!role && open === '[' && /^(inset-)?shadow$/.test(utility)) {
    // `shadow-[inset_0_0_0_1px_var(--x)]`: a ring, so a border.
    let depth = 0;
    let close = bracket + 1;
    for (; close < text.length; close++) {
      if (text[close] === '[') depth++;
      else if (text[close] === ']' && --depth === 0) break;
    }
    if (isRingShadow(text.slice(bracket + 2, close).replace(/_/g, ' '))) role = 'border';
  }
  return {
    active: variants.some((variant) => ACTIVE_VARIANT.test(variant.replace(/\/[\w-]+$/, ''))),
    hover: variants.some(isHoverVariant),
    placeholder: variants.includes('placeholder') || utility === 'placeholder',
    role,
    stack: utility === 'z',
    where: `${head}-${open}…${open === '[' ? ']' : ')'}`,
  };
}

/*
 * A box-shadow that draws a ring, one shadow with no offset nor blur and a spread
 * (`inset 0 0 0 1px var(--x)`): it paints a border, so its colour takes the border role.
 */
function isRingShadow(value) {
  const shadows = splitTopLevel(value.trim(), (char) => char === ',');
  if (shadows.length !== 1) return false;
  const parts = splitTopLevel(shadows[0].trim(), (char) => /\s/.test(char)).filter((part) => part && part !== 'inset');
  const length = (part) => /^-?(\d*\.)?\d+([a-z]+)?$/i.test(part);
  return parts.length === 5 && parts.slice(0, 4).every(length) && parts.slice(0, 3).every((part) => parseFloat(part) === 0)
    && parseFloat(parts[3]) > 0 && !length(parts[4]);
}

/* ------------------------------------------------------------------------- selectors */

/* Splits on a separator found outside (), [] and quotes. */
function splitTopLevel(text, isSeparator) {
  const parts = [];
  let depth = 0;
  let quote = null;
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (quote) {
      if (char === quote && text[i - 1] !== '\\') quote = null;
    } else if (char === '"' || char === '\'') {
      quote = char;
    } else if (char === '(' || char === '[') {
      depth++;
    } else if (char === ')' || char === ']') {
      depth--;
    } else if (depth === 0 && isSeparator(char)) {
      parts.push(text.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(text.slice(start));
  return parts;
}

/* A compound selector without what it negates or looks inside: `:not(:hover)` is not a hover. */
function withoutNegations(compound) {
  let output = '';
  let i = 0;
  while (i < compound.length) {
    const negation = compound.slice(i).match(/^:(not|has)\(/);
    if (!negation) {
      output += compound[i++];
      continue;
    }
    let depth = 0;
    let j = i + negation[0].length - 1;
    for (; j < compound.length; j++) {
      if (compound[j] === '(') depth++;
      else if (compound[j] === ')' && --depth === 0) break;
    }
    i = j + 1;
  }
  return output;
}

const selectorList = (selector) => splitTopLevel(selector, (char) => char === ',').map((part) => part.trim()).filter(Boolean);
const subjectOf = (complex) => splitTopLevel(complex, (char) => /[\s>+~]/.test(char)).filter(Boolean).pop() ?? '';
const isRootCompound = (compound) => /^&?(html|body)(?![\w-])/.test(compound) || /:root(?![\w-])/.test(compound);
const PLACEHOLDER_PSEUDO = /::?(?:-webkit-input-|-moz-)?placeholder(?![\w-])/;

/*
 * What each selector of a (possibly nested) rule targets: hover when a compound of the selector
 * (or of a parent rule) is in a :hover state, so the declaration only paints while hovering
 * (`.card:hover .icon`), never inside `:not()` / `:has()`; placeholder and document root are
 * read on the subject compound only. A nested selector whose subject holds `&` adds to the
 * subject of its parent.
 */
function selectorStates(chain) {
  let parents = [{ active: false, focus: false, hover: false, placeholder: false, root: false }];
  for (const selector of chain) {
    const next = [];
    for (const complex of selectorList(selector)) {
      const compound = withoutNegations(subjectOf(complex));
      const hover = HOVER_PSEUDO.test(withoutNegations(complex));
      const own = { active: ACTIVE_PSEUDO.test(withoutNegations(complex)), focus: FOCUS_PSEUDO.test(withoutNegations(complex)), hover, placeholder: PLACEHOLDER_PSEUDO.test(compound), root: isRootCompound(compound) };
      for (const parent of parents) {
        next.push({
          active: own.active || parent.active,
          focus: own.focus || parent.focus,
          hover: own.hover || parent.hover,
          placeholder: own.placeholder || (parent.placeholder && compound.includes('&')),
          root: own.root || (parent.root && compound.startsWith('&')),
        });
      }
    }
    if (next.length) parents = next;
  }
  return parents;
}

/* `all`, `none` or `mixed` for each state over the selectors of the list. */
function summarize(list) {
  const of = (key) => (list.every((state) => state[key]) ? 'all' : list.some((state) => state[key]) ? 'mixed' : 'none');
  return { active: of('active'), focus: of('focus'), hover: of('hover'), placeholder: of('placeholder'), root: of('root') };
}

/* `border: { color: … }` in SCSS: postcss-scss reads the group as a rule whose selector is `border:`. */
const isNestedProperty = (rule) => rule.type === 'rule' && /^[a-z-]+:$/.test(rule.selector.trim());
function fullProperty(node) {
  let { prop } = node;
  for (let parent = node.parent; parent && isNestedProperty(parent); parent = parent.parent) {
    prop = `${parent.selector.trim().slice(0, -1)}-${prop}`;
  }
  return prop;
}

/* The selectors from the outermost rule to the rule of the node; at-rules and nested SCSS properties do not count. */
function chainOf(node) {
  const chain = [];
  for (let parent = node.parent; parent && parent.type !== 'root'; parent = parent.parent) {
    if (parent.type === 'rule' && !isNestedProperty(parent)) chain.unshift(parent.selector);
  }
  return chain;
}

const ruleStates = new WeakMap();
function stateOf(node) {
  const rule = node.parent;
  if (!rule || rule.type === 'root') {
    return summarize([{}]);
  }
  if (!ruleStates.has(rule)) {
    ruleStates.set(rule, summarize(selectorStates(chainOf(node))));
  }
  return ruleStates.get(rule);
}

/*
 * The selectors that a CSS template opens before `head` (`:root {`, `&:hover {`), outermost
 * first, read with the same rules as a stylesheet.
 */
function templateChain(head) {
  const stack = [];
  let boundary = 0;
  for (let i = 0; i < head.length; i++) {
    const char = head[i];
    if (char === '{') {
      stack.push(head.slice(boundary, i).trim());
      boundary = i + 1;
    } else if (char === '}') {
      stack.pop();
      boundary = i + 1;
    } else if (char === ';') {
      boundary = i + 1;
    }
  }
  return stack;
}

/* The function calls (and `#{` interpolations) still open at the end of `text`, innermost first. */
function openCalls(text) {
  const stack = [];
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (char === '#' && text[i + 1] === '{') {
      stack.push('#{');
      i++;
    } else if (char === '(') {
      stack.push(text.slice(0, i).match(/[\w.-]*$/)[0]);
    } else if (char === ')' && stack.length && stack.at(-1) !== '#{') {
      stack.pop();
    } else if (char === '}' && stack.at(-1) === '#{') {
      stack.pop();
    }
  }
  return stack.reverse();
}
const insideMath = (head) => openCalls(head).some((name) => MATH.test(name));

