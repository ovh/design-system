/**
 * Resolves one v19 token. `context.role` is what it paints, `context.palette` says the token
 * is the value of an ODS token declaration (a theme), which reads the palette in v20.
 * `context.math` says the value is computed (calc), `context.root` that the selector targets
 * the document root; `hoverMixed` / `placeholderMixed` / `rootMixed` that the selector list mixes.
 */
function resolveToken(mapping, name, context = {}) {
  const entry = mapping.tokens[name];
  if (!entry) {
    return { note: `${name}: ${mapping.hints.unknown}` };
  }
  if (entry.todo) {
    return { todo: `${name}: ${hintOf(mapping, entry)}${entry.to ? ` (candidate \`${entry.to}\`)` : ''}` };
  }
  if (entry.keep) {
    if (entry.hint) return { todo: `${name}: ${hintOf(mapping, entry)}` };
    return entry.note ? { note: `${name}: ${entry.note}` } : {};
  }
  // A stacking rank is renamed only when a z-index reads it as is: computed, or kept in a variable
  // that may be computed further on, it is never pointed at a layer (what it must clear is the app's call).
  if (entry.rerank && (context.math || !context.stack)) {
    return { todo: `${name}: check this stacking: ${rerankHint(mapping, entry)}` };
  }
  // Removed, but what it held is known: a read paints the same (BC-25); declaring it is marked (declaredName).
  if (entry.to === null && entry.read) {
    return { note: `${name} → ${entry.read}: ${hintOf(mapping, entry).replace(/^removed: /, 'removed, so a read now takes the value it held. ')}`, to: entry.read };
  }
  if ('to' in entry) {
    if (entry.to) {
      const atRoot = contextTarget(entry, context.role ?? '*', context);
      const to = (context.root && atRoot) || entry.to;
      const mixed = context.rootMixed && atRoot && atRoot !== entry.to ? `${MIXED_ROOT} \`${atRoot}\` fits the root, split the rule.` : null;
      const note = joinNotes(entry.note, odsReads(mapping, entry, '*', to), mixed, rootAlias(context, atRoot, to));
      return note ? { note: `${name} → ${to}: ${note}`, to } : { to };
    }
    return { todo: entry.hint ? `${name}: ${hintOf(mapping, entry)}` : `${name} has no v20 equivalent: ${hintOf(mapping, entry)}` };
  }
  if (context.palette && entry.palette) {
    return { note: `${name} → ${entry.palette}: your theme now sets the same colour from the v20 palette; compare it on screen`, to: entry.palette };
  }
  if (context.alias && context.whole && !context.role && entry.palette) {
    return { note: paletteAliasNote(name, entry), to: entry.palette };
  }
  if (!context.role) {
    const roles = ['surface', 'border', 'content'].filter((role) => entry.byRole[role]);
    const likely = roles.includes(context.likely) ? context.likely : null;
    const candidates = roles.filter((role) => role !== likely).map((role) => `${ROLE_LABEL[role]} → \`${entry.byRole[role]}\``);
    const lead = likely ? ` Most likely here (a ${ROLE_LABEL[likely]}): \`${entry.byRole[likely]}\`.${candidates.length ? ` Otherwise: ${candidates.join(', ')}.` : ''}` : ` ${candidates.join(', ')}.`;
    const palette = entry.paletteValue ? ` To keep the exact v19 colour whatever the theme: var(${entry.paletteValue}).` : '';
    return { todo: `${name}: ${mapping.hints.role}${lead}${palette}` };
  }
  // The outline of a focused element is the focus ring, which v20 paints with its own role (the v19 theme outline colour's).
  const focus = mapping.tokens['--ods-theme-outline-color']?.to;
  if (context.focusRing && context.role === 'border' && entry.byRole.border && focus) {
    return { to: focus };
  }
  // A selector list that mixes a state and the rest: one value cannot be both.
  const rest = entry.byRole[context.role];
  for (const [mixed, cell, label] of [['hoverMixed', `${context.role}:hover`, 'a :hover state'], ['placeholderMixed', 'content:placeholder', 'a ::placeholder']]) {
    if (context[mixed] && entry.byRole[cell] && rest && entry.byRole[cell] !== rest) {
      return { todo: `${name}: this selector list mixes ${label} and the rest: \`${rest}\` at rest, \`${entry.byRole[cell]}\` for the other, split the rule` };
    }
  }
  const key = (context.placeholder && entry.byRole['content:placeholder'] && 'content:placeholder')
    || (context.active && entry.byRole[`${context.role}:active`] && `${context.role}:active`)
    || (context.hover && entry.byRole[`${context.role}:hover`] && `${context.role}:hover`)
    || context.role;
  const atRoot = contextTarget(entry, context.role, context);
  const to = (context.root && atRoot) || entry.byRole[key];
  if (!to) {
    return { todo: `${name} has no v20 equivalent as a ${ROLE_LABEL[context.role]}: pick another v20 colour (\`--ods-semantic-color-*\`, listed in the ODS design tokens guide), or write your own value` };
  }
  const mixed = joinNotes(context.rootMixed && atRoot && atRoot !== to ? `${MIXED_ROOT} \`${atRoot}\` fits the root, split the rule.` : null, rootAlias(context, atRoot, to)) || null;
  const ods = odsReads(mapping, entry, key, to);
  if (ods) {
    return { note: `${name} → ${to} as a ${ROLE_LABEL[context.role]}: ${joinNotes(ods, mixed)}`, to };
  }
  // An interaction token is only doubtful as a static colour: under :hover it is the intent.
  if (entry.doubtful?.includes(context.role) && !(context.hover && /interaction-/.test(to)) && !(context.root && atRoot)) {
    return { note: `${name} → ${to} as a ${ROLE_LABEL[context.role]}: v20 has no exact equivalent, this is the closest colour; compare it on screen. ${joinNotes(mixed)}`.trimEnd(), to };
  }
  return mixed ? { note: `${name} → ${to}: ${mixed}`, to } : { to };
}

/**
 * How a declared property is read, the same in a stylesheet, a style object and a CSS template:
 * an ODS token declaration is a theme (its value reads the palette), any other property paints
 * a role, at rest or in the state its selector says.
 */
function declarationContext(prop, state = {}) {
  if (prop.startsWith('--ods-')) {
    return { palette: true, placeholder: /placeholder/.test(prop), role: roleOfProperty(prop.replace(/^--ods-semantic-color-/, '--')) };
  }
  // On the document root, only the background is the page: a colour, a border or an alias of the app stays a surface.
  const page = PAGE_BACKGROUND.test(prop);
  return {
    alias: isPaletteAliasName(prop),
    active: state.active === 'all' || /-active$/.test(prop),
    focusRing: state.focus === 'all' && FOCUS_RING.test(prop),
    hover: state.hover === 'all' || /-(hover|active)$/.test(prop),
    likely: likelyRoleOfProperty(prop),
    hoverMixed: state.hover === 'mixed',
    placeholder: state.placeholder === 'all' || /placeholder/.test(prop),
    placeholderMixed: state.placeholder === 'mixed',
    role: roleOfProperty(prop),
    root: page && state.root === 'all',
    rootAlias: prop.startsWith('--') && state.root === 'all',
    rootMixed: page && state.root === 'mixed',
    stack: prop === 'z-index',
  };
}

/*
 * What becomes of the name of an ODS token that the app declares (`--ods-theme-x: …`): its
 * v20 name, or a marker when v20 has none or when it is a stacking rank to check (`rerank`).
 */
function declaredName(mapping, name) {
  const entry = mapping.tokens[name];
  if (entry.todo || (entry.keep && entry.hint)) {
    return { extra: [], todo: resolveToken(mapping, name).todo };
  }
  if (entry.to === null && entry.read) {
    return { extra: [], todo: `${name}: ${hintOf(mapping, entry)}` };
  }
  if (entry.keep) {
    return { extra: [], note: entry.note ? `${name}: ${entry.note}` : null };
  }
  if (entry.rerank) {
    return { extra: [], todo: `${name}: check this stacking: ${rerankHint(mapping, entry)}` };
  }
  const to = entry.to ?? (!('to' in entry) && entry.palette ? entry.palette : null);
  if (!to) {
    return { extra: [], todo: `${name}: ${'to' in entry ? hintOf(mapping, entry) : mapping.hints.declaration}` };
  }
  let note;
  if (!('to' in entry)) {
    const shared = entry.paletteShared ?? [];
    const fed = shared.length > 4 ? `${shared.slice(0, 4).join(', ')} and ${shared.length - 4} more` : shared.join(', ');
    note = `${name}: ${mapping.hints.declaration}${shared.length ? ` ${mapping.hints.shared} ${fed}, which it recolours too.` : ''}`;
  } else {
    const text = joinNotes(entry.note, odsReads(mapping, entry, '*', to));
    note = text ? `${name} → ${to}: ${text}` : null;
  }
  return { extra: entry.alsoDeclare ?? [], note, to };
}

/* The v20 name a declaration of `name` gets, when it gets one (used to find two declarations that collide). */
function declaredTarget(mapping, name) {
  const entry = mapping.tokens[name];
  if (!entry) {
    return name.startsWith('--ods-') ? name : null;
  }
  if (entry.todo || entry.keep || entry.rerank) {
    return null;
  }
  return entry.to ?? (!('to' in entry) && entry.palette ? entry.palette : null);
}

/* The v19 token of a value that resolves, as a theme value, to `target`: what makes `--X: var(--X)`. */
function selfReference(mapping, value, target) {
  const { token } = patternsOf(mapping);
  return [...value.matchAll(token)].map(([name]) => name).find((name) => resolveToken(mapping, name, { palette: true, role: null }).to === target);
}
const readsItself = (value, target) => new RegExp(`var\\(\\s*${escapeRegExp(target)}\\s*[,)]`).test(value);

const collisionMessage = (name, other, to) => `${name} and ${other} both become ${to} in v20: keep one value`;
const selfMessage = (name, other, to) => `${name} and ${other} both become ${to} in v20: remove this declaration`;

function createReport() {
  return { changes: [], notes: [], todos: [], typed: [], untyped: [] };
}

function sortReport(report) {
  for (const list of Object.values(report)) {
    list.sort((a, b) => a.line - b.line);
  }
  return report;
}

const hasWork = (source, mapping) => {
  const { hasMixinName, hasModifier, hasNumber, hasScss, hasTailwindKey, hasToken } = patternsOf(mapping);
  return hasToken.test(source) || hasScss.test(source) || HAS_OLD_FONT.test(source) || hasNumber.test(source) || hasMixinName.test(source)
    || hasModifier.test(source) || hasTailwindKey.test(source) || DYNAMIC.test(source)
    || (THEMES_IMPORT.test(source) && /\$ods-/.test(source)) || CONTROL.test(source)
    || /--ods-[a-z0-9-]*#\{[^}]*\}[a-z0-9-]*\s*:/.test(source) || (/z-index/.test(source) && OVERLAY_PART.test(source)) || LINK_PART.test(source) || /ods-link\s*\(/.test(source) || ACCENT_TAG_HOST.test(source);
};

/* A token that v20 still declares but no longer reads: reading it works, overriding it does nothing. */
const isOverrideOnly = (mapping, name) => Boolean(mapping.tokens[name]?.overrideOnly);

/* ------------------------------------------------------------------------- text (strings, @apply) */

/* Where the value of a declaration that starts at `start` ends: its `;`, the `}` of its block, or the end. */
function endOfValue(text, start) {
  let depth = 0;
  for (let i = start; i < text.length; i++) {
    if (text[i] === '(') depth++;
    else if (text[i] === ')') depth--;
    else if (depth <= 0 && (text[i] === ';' || text[i] === '}')) return i;
  }
  return text.length;
}

const applyEdits = (text, edits) => [...edits].sort((a, b) => b.start - a.start).reduce((output, item) => output.slice(0, item.start) + item.text + output.slice(item.end), text);

/**
 * The tokens written in one piece of text (a string of a script, the params of `@apply`, a
 * quoted SCSS string), as edits relative to the text. `env.before` is the text of the same
 * template before it; `env.keyContext` the context given by the key the text is the value of;
 * `env.role` the role when nothing in the text says one; `env.dynamicTail` that the text goes on
 * with a value computed at runtime; `env.css: false` that the text holds no CSS declaration;
 * `env.themeKeys` the Tailwind keys whose theme definition the same run renames.
 */
function planText(mapping, text, env = {}) {
  const out = { edits: [], notes: [], todos: [] };
  const { modifier, tailwindKey, token } = patternsOf(mapping);
  const before = env.before ?? '';
  const { config } = env;
  let limit = text.length;
  // `var(--ods-color-${status}-500)`: the name is built at runtime, a rename would truncate it.
  if (env.dynamicTail) {
    const tail = text.match(/--ods-[a-z0-9-]*$/);
    if (tail && isTokenPrefix(mapping, tail[0])) {
      out.todos.push(`${tail[0]}…: token name built at runtime: map each value by hand`);
      limit = tail.index;
    }
  }
  for (const match of text.slice(0, limit).matchAll(/--ods-[a-z0-9-]*#\{/g)) {
    const prefix = match[0].slice(0, -2);
    if (isTokenPrefix(mapping, prefix)) out.todos.push(`${prefix}#{…}: token name built at runtime: map each value by hand`);
  }
  let skipUntil = 0;
  for (const match of text.slice(0, limit).matchAll(token)) {
    const name = match[0];
    const offset = match.index;
    const end = offset + name.length;
    if (offset < skipUntil || /^-?#\{/.test(text.slice(end))) {
      continue;
    }
    const head = before + text.slice(0, offset);
    // `--ods-theme-x: value;` in a CSS template: a declaration of the token, a theme.
    if (env.css !== false && name in mapping.tokens && /^\s*:/.test(text.slice(end)) && /(^|[\s;{])$/.test(head)) {
      const valueStart = text.indexOf(':', end) + 1;
      const valueEnd = endOfValue(text, valueStart);
      const declaration = planDeclarationText(mapping, name, text.slice(valueStart, valueEnd), { config, siblings: declaredBefore(head) });
      out.todos.push(...declaration.todos);
      out.notes.push(...declaration.notes);
      if (declaration.to) {
        out.edits.push({ end, message: declaration.message, start: offset, text: declaration.to });
      }
      declaration.edits.forEach((item) => out.edits.push({ ...item, end: item.end + valueStart, start: item.start + valueStart }));
      if (declaration.extra.length && env.fragment) {
        // A quoted string, not a stylesheet: a test that looks for this declaration in some CSS. Where the
        // migrated CSS writes the second one (next line, same line) is not known here.
        out.todos.push(`${name}: v20 splits it into ${[declaration.to ?? name, ...declaration.extra].join(' and ')}: this string now names the first one; if it is looked for in a stylesheet, look for the other one too, as that stylesheet writes it`);
      } else if (declaration.extra.length) {
        const close = text[valueEnd] === ';' ? valueEnd + 1 : valueEnd;
        const value = applyEdits(text.slice(valueStart, valueEnd), declaration.edits).trim();
        const inserted = declaration.extra.map((prop) => `${prop}: ${value};`).join(' ');
        out.edits.push({ end: close, message: declaration.message, start: close, text: `${text[valueEnd] === ';' ? ' ' : '; '}${inserted}` });
      }
      skipUntil = valueEnd;
      continue;
    }
    const tailwind = tailwindContext(text, offset);
    if (isOverrideOnly(mapping, name) && (tailwind || /var\(\s*$/.test(head))) {
      continue;
    }
    let context;
    if (tailwind) {
      // `z-[calc(var(--ods-…)+1)]`: the arbitrary value is computed, as in a declaration.
      context = { ...tailwind, config, math: insideMath(head) };
    } else if (env.keyContext) {
      context = { ...env.keyContext, config, math: insideMath(head) };
    } else {
      // A CSS declaration written in a template: its property is on the same line, before the token.
      const declaration = env.css === false ? null : head.split('\n').pop().match(/([a-zA-Z-]+)\s*:[^:;{}]*$/);
      context = declaration
        ? { ...declarationContext(declaration[1], summarize(selectorStates(templateChain(head)))), config, math: insideMath(head) }
        : { config, math: insideMath(head), role: env.role ?? null };
    }
    if (/gradient\(/.test(head.slice(Math.max(0, head.lastIndexOf(';'))))) {
      context = { ...context, likely: context.likely ?? context.role, role: null };
    }
    // The value of a key is `var(--ods-…)` alone (with a fallback or not): the whole value is one token.
    const whole = /^\s*var\(\s*$/.test(text.slice(0, offset)) && /^\s*(,[^()]*)?\)\s*$/.test(text.slice(end));
    const result = resolveToken(mapping, name, { ...context, whole });
    if (result.to) {
      out.edits.push({ end, message: `${name} → ${result.to}${tailwind ? ` (${tailwind.where})` : ''}`, start: offset, text: result.to });
    }
    if (result.todo) out.todos.push(result.todo);
    if (result.note) out.notes.push(result.note);
  }
  for (const match of keepsOldFont(config) ? [] : text.matchAll(OLD_FONT)) {
    out.edits.push({ end: match.index + match[0].length, message: '\'Source Sans Pro\' → \'Source Sans 3\'', start: match.index, text: `${match[1] ?? ''}Source Sans 3${match[1] ?? ''}` });
  }
  for (const match of text.matchAll(OLD_FONT_PATH)) {
    const start = match.index + match[1].length;
    out.edits.push({ end: start + 'source-sans-pro'.length, message: 'source-sans-pro → source-sans-3', start, text: 'source-sans-3' });
  }
  for (const match of text.matchAll(modifier)) {
    for (const item of planModifier(mapping, text, match, env.hashed !== false, config)) {
      if (item.todo) out.todos.push(item.todo);
      else if (item.note) out.notes.push(item.note);
      else out.edits.push(item);
    }
  }
  // A utility follows its theme key: renamed alone, it would name a class that no theme defines.
  for (const match of text.matchAll(tailwindKey)) {
    const to = mapping.tailwindKeys[match[1]];
    if (!to) {
      out.todos.push(noTailwindKey(match[1]));
    } else if (env.themeKeys?.has(match[1])) {
      out.edits.push({ end: match.index + match[1].length, message: `${match[1]} → ${to} (Tailwind key)`, start: match.index, text: to });
    } else {
      out.todos.push(`${match[1]}: a Tailwind key of the ODS guide, \`${to}\` in v20: rename it in your Tailwind theme (tailwind.config, a preset or \`@theme\`) and in its utilities together`);
    }
  }
  return out;
}

const noTailwindKey = (key) => `${key}: a Tailwind key of the ODS v19 guide with no v20 name: give it one that says what it paints (\`ods-surface-*\`, \`ods-content-*\`, \`ods-border-*\`, \`ods-container\`, \`ods-control\`… in the Tailwind guide), in your Tailwind theme and in its utilities together`;

/* The configurator keeps 'Source Sans Pro' (the opt-out CSS declares it first): the family name stays, the ODS asset paths still move. */
const keepsOldFont = (config) => isV19Look(config, 'font-family');

/* The ODS tokens a CSS template declares before `head`, in the same block: siblings of a declaration. */
function declaredBefore(head) {
  const block = head.slice(head.lastIndexOf('{') + 1);
  return [...block.matchAll(/(?:^|[\s;])(--ods-[a-z0-9-]+)\s*:/g)].map((match) => match[1]);
}

/*
 * A declaration of an ODS token in a script (an object key, or `--x: …` in a template): its new
 * name, its value read as a theme value, and the guards of a stylesheet (self-reference,
 * collision with a sibling, `alsoDeclare`).
 */
function planDeclarationText(mapping, name, valueText, { config, siblings = [] } = {}) {
  const out = { edits: [], extra: [], notes: [], todos: [] };
  const declared = declaredName(mapping, name);
  if (declared.todo) out.todos.push(declared.todo);
  const value = planText(mapping, valueText, { config, css: false, keyContext: declarationContext(declared.to ?? name) });
  if (!declared.to) {
    if (declared.note) out.notes.push(declared.note);
    out.edits = value.edits;
    out.todos.push(...value.todos);
    out.notes.push(...value.notes);
    return out;
  }
  if (readsItself(applyEdits(valueText, value.edits), declared.to)) {
    // `--ods-theme-input-border-width: var(--ods-theme-border-width)`: both are border-thickness in v20.
    out.todos.push(selfMessage(name, selfReference(mapping, valueText, declared.to) ?? declared.to, declared.to));
    return out;
  }
  out.to = declared.to;
  out.edits = value.edits;
  out.todos.push(...value.todos);
  out.notes.push(...[declared.note, ...value.notes].filter(Boolean));
  const other = siblings.find((sibling) => sibling !== name && declaredTarget(mapping, sibling) === declared.to);
  if (other) out.todos.push(collisionMessage(name, other, declared.to));
  out.extra = declared.extra.filter((prop) => !siblings.includes(prop));
  out.message = out.extra.length ? `${name} → ${declared.to} + ${out.extra.join(' + ')} (v20 splits what it set)` : `${name} → ${declared.to}`;
  return out;
}

/*
 * An internal class of a component (`button--ghost`) in a class attribute selector or in its
 * hashed CSS-module form (`_button--ghost_x1y2`): renamed by `cssModifiers`, marked when v20
 * has no class for it. A plain `.button--ghost` can be the app's own BEM: left alone.
 */
function planModifier(mapping, text, match, hashed, config) {
  const [, underscore, block, name] = match;
  const table = mapping.cssModifiers[block];
  if (!Object.hasOwn(table, name)) {
    return [];
  }
  const open = text.lastIndexOf('[', match.index);
  const inAttribute = open >= 0 && !text.slice(open, match.index).includes(']') && /^\[\s*class\s*[*^~$|]?=/.test(text.slice(open));
  if (!inAttribute && !(underscore && hashed)) {
    return [];
  }
  const subject = `${block}--${name}`;
  const rule = modifierRule(table[name], config);
  if (rule.hint) {
    return [{ todo: `${subject}: ${rule.hint}` }];
  }
  const { to } = rule;
  if (to === null) {
    return [{ todo: `${subject}: internal class with no v20 equivalent: select [data-ods="${block}"] and the props of the component instead` }];
  }
  const start = match.index + underscore.length;
  return [
    { end: start + subject.length, message: `${subject} → ${block}--${to} (internal class)`, start, text: `${block}--${to}` },
    { note: `${subject} → ${block}--${to}: internal class: prefer [data-ods="${block}"]` },
  ];
}

/*
 * One modifier of `cssModifiers`: `"low"`, `null`, or `{ to, choice, hint }` for a class whose
 * elements depend on a default of v20 (`button--default` also matched every Button without
 * `variant`, medium in Aluminium): renamed only when the config keeps the v19 look, which writes
 * that default out; marked with the hint otherwise.
 */
function modifierRule(entry, config) {
  if (entry === null || typeof entry === 'string') {
    return { to: entry };
  }
  return isV19Look(config, entry.choice) ? { to: entry.to } : { hint: entry.hint, to: entry.to };
}

